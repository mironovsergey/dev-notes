/**
 * B. Железные дороги
 *
 * https://contest.yandex.ru/contest/25070/problems/B/
 *
 * В стране X есть n городов, которым присвоены номера от 1 до n. Столица страны
 * имеет номер n. Между городами проложены железные дороги.
 *
 * Однако дороги могут быть двух типов по ширине полотна. Любой поезд может
 * ездить только по одному типу полотна. Условно один тип дорог помечают как R,
 * а другой как B. То есть если маршрут от одного города до другого имеет как
 * дороги типа R, так и дороги типа B, то ни один поезд не сможет по этому
 * маршруту проехать. От одного города до другого можно проехать только по
 * маршруту, состоящему исключительно из дорог типа R или только из дорог
 * типа B.
 *
 * Но это еще не все. По дорогам страны X можно двигаться только от города
 * с меньшим номером к городу с большим номером. Это объясняет большой приток
 * жителей в столицу, у которой номер n.
 *
 * Карта железных дорог называется оптимальной, если не существует пары городов
 * A и B такой, что от A до B можно добраться как по дорогам типа R, так и по
 * дорогам типа B. Иными словами, для любой пары городов верно, что от города
 * с меньшим номером до города с бОльшим номером можно добраться по дорогам
 * только какого-то одного типа или же что маршрут построить вообще нельзя.
 * Выясните, является ли данная вам карта оптимальной.
 *
 * Формат ввода
 * В первой строке дано число n (1 ≤ n ≤ 5000) - количество городов в стране.
 * Далее задана карта железных дорог в следующем формате.
 *
 * Карта задана n-1 строкой. В i-й строке описаны дороги из города i в города
 * i+1, i+2, ..., n. В строке записано n - i символов, каждый из которых либо R,
 * либо B. Если j-й символ строки i равен «B», то из города i в город i + j идет
 * дорога типа «B». Аналогично для типа «R».
 *
 * Формат вывода
 * Выведите «YES», если карта оптимальна, и «NO» в противном случае.
 *
 * Отчет: https://contest.yandex.ru/contest/25070/run-report/116170864/
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  // Чтение количества городов в стране
  const n = readInt();

  // Массив дорог
  const edges = [];

  for (let i = 1; i < n; i++) {
    edges.push(readLine().trim());
  }

  const adjacencyListR = createAdjacencyList(n, edges, 'R');
  const adjacencyListB = createAdjacencyList(n, edges, 'B');

  const isOptimality = !hasCommonPaths(n, adjacencyListR, adjacencyListB);

  process.stdout.write(`${isOptimality ? 'YES' : 'NO'}`);
}

/**
 * Создает список смежности для дорог одного типа.
 *
 * Карта задает полный ациклический граф: дорога есть между каждой парой
 * городов, и все они ведут от меньшего номера к большему. Ребер получается
 * n·(n−1)/2, то есть около 12,5 миллиона при n = 5000.
 *
 * Время: O(n²). Память: O(числа ребер данного типа).
 *
 * @param {number} n Количество городов.
 * @param {string[]} edges Строки карты: edges[i-1][j] - тип дороги i → i+j+1.
 * @param {string} type Тип дороги: 'R' или 'B'.
 * @returns {number[][]} Списки смежности графа дорог этого типа.
 */
function createAdjacencyList(n, edges, type) {
  const adjacencyList = Array.from({ length: n + 1 }, () => []);

  for (let i = 1; i < n; i++) {
    for (let j = 0; j < edges[i - 1].length; j++) {
      if (edges[i - 1][j] === type) {
        adjacencyList[i].push(i + j + 1);
      }
    }
  }

  return adjacencyList;
}

/**
 * Вычисляет времена входа и выхода для всех вершин обходом в глубину.
 *
 * Интервалы [entry[v], leave[v]] образуют правильную скобочную структуру:
 * два интервала либо не пересекаются, либо один вложен в другой. Вложенность
 * интервала j в интервал i означает, что j - потомок i в лесу обхода.
 *
 * Внешний цикл перебирает города по возрастанию номера. Это существенно:
 * нумерация является топологическим порядком графа, и запуск в произвольном
 * порядке сделал бы прием неверным.
 *
 * Время: O(|V| + |E|). Память: O(|V|), плюс глубина рекурсии до n.
 *
 * @param {number} n Количество городов.
 * @param {number[][]} adjacencyList Списки смежности.
 * @returns {{entry: number[], leave: number[]}} Времена входа и выхода.
 */
function computeTimings(n, adjacencyList) {
  const colors = Array(n + 1).fill('white');
  const entry = Array(n + 1).fill(null);
  const leave = Array(n + 1).fill(null);

  let time = 0;

  function dfs(startVertex) {
    time += 1;
    entry[startVertex] = time;
    colors[startVertex] = 'gray';

    for (let neighbor of adjacencyList[startVertex]) {
      if (colors[neighbor] === 'white') {
        dfs(neighbor);
      }
    }

    time += 1;
    leave[startVertex] = time;
    colors[startVertex] = 'black';
  }

  for (let i = 1; i <= n; i++) {
    if (colors[i] === 'white') {
      dfs(i);
    }
  }

  return { entry, leave };
}

/**
 * Проверяет, есть ли пара городов, связанная дорогами обоих типов.
 *
 * Для каждой пары проверяется, является ли второй город потомком первого
 * в лесу обхода - одновременно в графе дорог R и в графе дорог B.
 *
 * Важно понимать, что именно проверяется. Вложенность интервалов означает
 * достижимость, но обратное неверно: город может быть достижим, не будучи
 * потомком, если его успел занять более ранний обход. Тем не менее итоговый
 * ответ верен - если плохая пара существует, то существует и пара, являющаяся
 * парой «предок - потомок» в обоих лесах, пусть и другая.
 *
 * Подробный разбор, включая доказуемо корректный критерий через транзитивность
 * турнира, - в docs/sprint-6/railways.md.
 *
 * Время: O(n²). Память: O(n).
 *
 * @param {number} n Количество городов.
 * @param {number[][]} adjacencyListR Списки смежности дорог типа R.
 * @param {number[][]} adjacencyListB Списки смежности дорог типа B.
 * @returns {boolean} true, если найдена пара, связанная дорогами обоих типов.
 */
function hasCommonPaths(n, adjacencyListR, adjacencyListB) {
  const { entry: entryR, leave: leaveR } = computeTimings(n, adjacencyListR);
  const { entry: entryB, leave: leaveB } = computeTimings(n, adjacencyListB);

  for (let i = 1; i <= n; i++) {
    for (let j = i + 1; j <= n; j++) {
      if (
        entryR[i] < entryR[j] &&
        leaveR[i] > leaveR[j] &&
        entryB[i] < entryB[j] &&
        leaveB[i] > leaveB[j]
      ) {
        return true;
      }
    }
  }

  return false;
}

run(solve);
