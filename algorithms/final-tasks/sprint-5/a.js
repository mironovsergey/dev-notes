/**
 * A. Пирамидальная сортировка
 *
 * https://contest.yandex.ru/contest/24810/problems/A/
 *
 * В данной задаче необходимо реализовать сортировку кучей. При этом кучу
 * необходимо реализовать самостоятельно, использовать имеющиеся в языке
 * реализации нельзя.
 *
 * Тимофей решил организовать соревнование по спортивному программированию,
 * чтобы найти талантливых стажеров. Задачи подобраны, участники
 * зарегистрированы, тесты написаны. Осталось придумать, как в конце
 * соревнования будет определяться победитель.
 *
 * Каждый участник имеет уникальный логин. Когда соревнование закончится, к нему
 * будут привязаны два показателя: количество решенных задач Pᵢ и размер штрафа
 * Fᵢ. Штраф начисляется за неудачные попытки и время, затраченное на задачу.
 *
 * Тимофей решил сортировать таблицу результатов следующим образом: при
 * сравнении двух участников выше будет идти тот, у которого решено больше
 * задач. При равенстве числа решенных задач первым идет участник с меньшим
 * штрафом. Если же и штрафы совпадают, то первым будет тот, у которого логин
 * идет раньше в алфавитном (лексикографическом) порядке.
 *
 * Тимофей заказал толстовки для победителей и накануне поехал за ними
 * в магазин. В свое отсутствие он поручил вам реализовать алгоритм сортировки
 * кучей (англ. Heapsort) для таблицы результатов.
 *
 * Формат ввода
 * В первой строке задано число участников n, 1 ≤ n ≤ 100 000.
 * В каждой из следующих n строк задана информация про одного из участников.
 * i-й участник описывается тремя параметрами:
 * - уникальным логином (строкой из маленьких латинских букв длиной не более 20)
 * - числом решенных задач Pᵢ
 * - штрафом Fᵢ
 *
 * Fᵢ и Pᵢ - целые числа, лежащие в диапазоне от 0 до 10^9.
 *
 * Формат вывода
 * Для отсортированного списка участников выведите по порядку их логины
 * по одному в строке.
 *
 * Отчет: https://contest.yandex.ru/contest/24810/run-report/112166432/
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const n = readInt();
  const participants = new Array(n);

  for (let i = 0; i < n; i++) {
    const [login, solved, penalty] = readLine().trim().split(/\s+/);

    participants[i] = new Participant(login, Number(solved), Number(penalty));
  }

  const sorted = heapsort(participants);
  const output = new Array(n);

  for (let i = 0; i < n; i++) {
    output[i] = sorted[i].login;
  }

  // Накопление в массив вместо n вызовов write: при n до 10^5
  // это заметно дешевле по системным вызовам
  process.stdout.write(n === 0 ? '' : `${output.join('\n')}\n`);
}

// =============================================================================
/**
 * Участник соревнования
 * @class
 */
class Participant {
  /**
   * Создает участника
   * @param {string} login Логин участника
   * @param {number} solved Количество решенных задач
   * @param {number} penalty Штрафные баллы
   */
  constructor(login, solved, penalty) {
    this.login = login;
    this.solved = solved;
    this.penalty = penalty;
  }

  /**
   * Проверяет, должен ли текущий участник идти раньше другого.
   *
   * Порядок задан условием: больше решенных задач, при равенстве - меньший
   * штраф, при равенстве - логин раньше в лексикографическом порядке. Логины
   * уникальны, поэтому сравнение всегда разрешается и порядок строгий.
   *
   * Время: O(1) сверх сравнения логинов.
   *
   * @param {Participant} participant Другой участник.
   * @returns {boolean} true, если текущий участник приоритетнее.
   */
  compare(participant) {
    if (this.solved !== participant.solved) {
      // Сравнение по числу решенных задач
      return this.solved > participant.solved;
    } else if (this.penalty !== participant.penalty) {
      // Сравнение по штрафам
      return this.penalty < participant.penalty;
    } else {
      // Сравнение по логину
      return this.login < participant.login;
    }
  }
}

/**
 * Просеивает элемент вверх до восстановления свойства кучи.
 *
 * Итеративная версия: рекурсия здесь хвостовая, и цикл не расходует стек.
 *
 * Время: O(log n). Память: O(1).
 *
 * @param {Participant[]} heap Куча с фиктивным нулевым элементом.
 * @param {number} index Индекс просеиваемого элемента.
 * @returns {number} Индекс, на котором элемент остановился.
 */
function siftUp(heap, index) {
  let current = index;

  while (current > 1) {
    const parent = Math.floor(current / 2);

    if (!heap[current].compare(heap[parent])) {
      break;
    }

    [heap[current], heap[parent]] = [heap[parent], heap[current]];
    current = parent;
  }

  return current;
}

/**
 * Просеивает элемент вниз до восстановления свойства кучи.
 *
 * Обмен выполняется с наиболее приоритетным из детей: обмен с менее
 * приоритетным поставил бы его выше собственного брата и нарушил бы свойство
 * кучи заново.
 *
 * Граница size задается явно, чтобы сортировка могла просеивать по префиксу
 * массива, не трогая уже отсортированный хвост.
 *
 * Время: O(log n). Память: O(1).
 *
 * @param {Participant[]} heap Куча с фиктивным нулевым элементом.
 * @param {number} index Индекс просеиваемого элемента.
 * @param {number} size Количество элементов кучи.
 * @returns {number} Индекс, на котором элемент остановился.
 */
function siftDown(heap, index, size = heap.length - 1) {
  let current = index;

  for (;;) {
    const left = 2 * current;
    const right = 2 * current + 1;
    let best = current;

    if (left <= size && heap[left].compare(heap[best])) {
      best = left;
    }

    if (right <= size && heap[right].compare(heap[best])) {
      best = right;
    }

    if (best === current) {
      return current;
    }

    [heap[current], heap[best]] = [heap[best], heap[current]];
    current = best;
  }
}

/**
 * Превращает массив в кучу на месте алгоритмом Флойда.
 *
 * Листья просеивать не нужно: поддерево из одной вершины уже является кучей.
 * Обход идет от последней вершины, имеющей детей, к первой, поэтому к моменту
 * просеивания вершины оба ее поддерева уже корректные кучи.
 *
 * Построение поэлементными вставками стоило бы O(n log n); здесь O(n).
 *
 * Время: O(n). Память: O(1).
 *
 * @param {Participant[]} heap Массив с фиктивным нулевым элементом.
 * @returns {Participant[]} Тот же массив, упорядоченный как куча.
 */
function buildHeap(heap) {
  const size = heap.length - 1;

  for (let i = Math.floor(size / 2); i >= 1; i--) {
    siftDown(heap, i, size);
  }

  return heap;
}

/**
 * Сортирует участников пирамидальной сортировкой.
 *
 * Массив делится на префикс-кучу и отсортированный суффикс. На каждом шаге
 * корень кучи - наиболее приоритетный из оставшихся - меняется местами с ее
 * последним элементом и тем самым занимает свое окончательное место, после
 * чего граница кучи сдвигается влево, а новый корень просеивается вниз.
 *
 * Куча отдает участников от наиболее приоритетного к наименее, а заполнение
 * идет с конца, поэтому итоговый порядок - от наиболее приоритетного.
 *
 * Время: O(n log n) во всех случаях. Память: O(n) на копию с фиктивным
 * элементом.
 *
 * @param {Participant[]} array Массив участников.
 * @returns {Participant[]} Участники в порядке итоговой таблицы.
 */
function heapsort(array) {
  const heap = [null, ...array];

  buildHeap(heap);

  for (let size = array.length; size > 1; size--) {
    [heap[1], heap[size]] = [heap[size], heap[1]];
    siftDown(heap, 1, size - 1);
  }

  // Куча на максимум оставила элементы по возрастанию приоритета,
  // поэтому массив разворачивается
  const result = new Array(array.length);

  for (let i = 0; i < array.length; i++) {
    result[i] = heap[array.length - i];
  }

  return result;
}
// =============================================================================

run(solve);
