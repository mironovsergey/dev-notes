/**
 * A. Packed Prefix
 *
 * https://contest.yandex.ru/contest/26133/problems/A/
 *
 * Вам даны строки в запакованном виде. Определим запакованную строку (ЗС)
 * рекурсивно. Строка, состоящая только из строчных букв английского алфавита
 * является ЗС. Если A и B - корректные ЗС, то и AB является ЗС. Если A - ЗС,
 * а n - однозначное натуральное число, то n[A] тоже ЗС. При этом запись n[A]
 * означает, что при распаковке строка A записывается подряд n раз. Найдите
 * наибольший общий префикс распакованных строк и выведите его (в распакованном
 * виде).
 *
 * Формат ввода
 * В первой строке записано число n (1 ≤ n ≤ 1000) - число строк.
 *
 * Далее в n строках записаны запакованные строки. Гарантируется, что эти строки
 * корректны, то есть удовлетворяют указанному рекурсивному определению. Длина
 * строк после распаковки не превосходит 10^5.
 *
 * Формат вывода
 * Выведите наибольший общий префикс распакованных строк.
 *
 * Примечания
 * Сложение подразумевается как конкатенация двух строк. Умножение строки
 * на число - повтор строки соответствующее число раз. Пусть функция f умеет
 * принимать ЗС и распаковывать ее. Если ЗС D имеет вид D=AB, где A и B тоже ЗС,
 * то f(D) = f(A) + f(B). Если D = n[A], то f(D) = f(A) × n.
 *
 * Отчет: https://contest.yandex.ru/contest/26133/run-report/116763954/
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const n = readInt(); // Число строк
  const lines = []; // Массив строк

  for (let i = 1; i <= n; i++) {
    lines.push(readLine());
  }

  process.stdout.write(`${longestCommonPrefix(lines)}`);
}

/**
 * Находит наибольший общий префикс распакованных строк.
 *
 * Строки распаковываются, после чего префикс укорачивается по каждой следующей
 * строке посимвольным сравнением с начала до первого расхождения.
 *
 * Через префикс-функцию строки «A # B» эту задачу решать нельзя: значение
 * pi[j] равно длине наибольшего префикса A, совпадающего с суффиксом, который
 * оканчивается в позиции j, - то есть характеризует вхождения A внутрь B, а не
 * общее начало двух строк. Максимум таких значений дает наибольшую подстроку
 * B, являющуюся префиксом A, что с искомым ответом не совпадает.
 *
 * Время: O(L), где L - суммарная длина распакованных строк. Память: O(L).
 *
 * @param {string[]} lines Запакованные строки.
 * @returns {string} Наибольший общий префикс распакованных строк.
 */
function longestCommonPrefix(lines) {
  const unpacked = lines.map(parseLine);
  let prefixLength = unpacked[0].length;

  for (let i = 1; i < unpacked.length; i++) {
    const current = unpacked[i];
    let common = 0;

    while (
      common < prefixLength &&
      common < current.length &&
      unpacked[0][common] === current[common]
    ) {
      common++;
    }

    prefixLength = common;

    // Пустой префикс укоротить уже нельзя - остальные строки можно не смотреть
    if (prefixLength === 0) {
      break;
    }
  }

  return unpacked[0].slice(0, prefixLength);
}

/**
 * Распаковывает строку, закодированную в формате n[A],
 * где n - однозначное число, A - строка
 *
 * @param {string} line Запакованная строка
 * @returns {string} Распакованная строка
 */
function parseLine(line) {
  const stack = [];

  let str = '';
  let num = 0;

  for (let char of line) {
    if (char >= '0' && char <= '9') {
      num = parseInt(char);
    } else if (char === '[') {
      // Начало новой запакованной последовательности,
      // сохранение текущей строки и числа в стеке
      stack.push(str);
      stack.push(num);

      str = '';
      num = 0;
    } else if (char === ']') {
      // Конец запакованной последовательности,
      // извлечение данных из стека
      const currNum = stack.pop();
      const prevStr = stack.pop();

      // Повторение текущей строки currNum раз
      let currstr = '';

      for (let i = 0; i < currNum; i++) {
        currstr += str;
      }

      // Конкатенация с предыдущей строкой
      str = prevStr + currstr;
    } else {
      str += char;
    }
  }

  return str;
}

run(solve);
