/**
 * B. Шпаргалка
 *
 * https://contest.yandex.ru/contest/26133/problems/B/
 *
 * Вася готовится к экзамену по алгоритмам и на всякий случай пишет шпаргалки.
 *
 * Чтобы уместить на них как можно больше информации, он не разделяет слова
 * пробелами. В итоге получается одна очень длинная строка. Чтобы на самом
 * экзамене из-за нервов не запутаться в прочитанном, он просит вас написать
 * программу, которая по этой длинной строке и набору допустимых слов определит,
 * можно ли разбить текст на отдельные слова из набора.
 *
 * Более формально: дан текст T и набор строк s₁, ... ,sₙ. Надо определить,
 * представим ли T как sₖ₁sₖ₂...sₖᵣ, где ₖᵢ - индексы строк. Индексы могут
 * повторяться. Строка sᵢ может встречаться в разбиении текста T произвольное
 * число раз. Можно использовать не все строки для разбиения. Строки могут идти
 * в любом порядке.
 *
 * Формат ввода
 * В первой строке дан текст T, который надо разбить на слова. Длина T
 * не превосходит 100100. Текст состоит из строчных букв английского алфавита.
 *
 * Во второй строке записано число допустимых к использованию слов 1 ≤ n ≤ 100.
 *
 * В последующих n строках даны сами слова, состоящие из маленьких латинских
 * букв. Длина каждого слова не превосходит 100.
 *
 * Формат вывода
 * Выведите «YES», если текст можно разбить на слова из данного словаря,
 * или «NO» в ином случае.
 *
 * Отчет: https://contest.yandex.ru/contest/26133/run-report/116738248/
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const text = readLine(); // Текст, который надо разбить на слова
  const n = readInt(); // Число допустимых к использованию слов
  const words = []; // Массив слов

  for (let i = 1; i <= n; i++) {
    words.push(readLine());
  }

  process.stdout.write(`${canBeSegmented(text, words) ? 'YES' : 'NO'}`);
}

class Node {
  constructor() {
    // Объект, который хранит переходы по символам к дочерним узлам
    this.children = {};

    // Булевое значение, указывающее, является ли узел терминальным
    this.isTerminal = false;
  }
}

class Trie {
  constructor() {
    this.root = new Node();
  }

  /**
   * Добавляет слово в префиксное дерево
   *
   * @param {string} word Слово для добавления
   */
  add(word) {
    let node = this.root;

    for (const char of word) {
      if (!(char in node.children)) {
        node.children[char] = new Node();
      }

      node = node.children[char];
    }

    node.isTerminal = true;
  }
}

/**
 * Определяет, можно ли разбить текст на слова из словаря.
 *
 * Динамическое программирование по позициям текста: dp[i] означает, что
 * префикс длины i разбивается на слова словаря. База dp[0] = true - пустой
 * префикс разбивается пустым набором слов.
 *
 * Переход из достижимой позиции i выполняется спуском по префиксному дереву:
 * один спуск сразу проверяет все слова, начинающиеся с текущего символа,
 * и отмечает достижимой каждую позицию, где заканчивается слово словаря.
 * Перебор слов по одному потребовал бы проверки каждого из n слов в каждой
 * из |T| позиций.
 *
 * Время: O(|T| · m), где m - длина наибольшего слова. Память: O(|T| + L),
 * где L - суммарная длина слов.
 *
 * @param {string} text Текст, который нужно разбить на слова.
 * @param {string[]} words Допустимые слова.
 * @returns {boolean} true, если текст разбивается на слова словаря.
 */
function canBeSegmented(text, words) {
  const trie = new Trie();

  for (const word of words) {
    trie.add(word);
  }

  const dp = new Array(text.length + 1).fill(false);

  dp[0] = true;

  for (let i = 0; i < text.length; i++) {
    if (dp[i]) {
      let node = trie.root;

      for (let j = i; j < text.length; j++) {
        if (!(text[j] in node.children)) {
          break;
        }

        node = node.children[text[j]];

        if (node.isTerminal) {
          dp[j + 1] = true;
        }
      }
    }
  }

  return dp[text.length];
}

run(solve);
