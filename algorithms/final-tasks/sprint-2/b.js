/**
 * B. Калькулятор
 *
 * https://contest.yandex.ru/contest/22781/problems/B/
 *
 * Задание связано с обратной польской нотацией. Она используется для парсинга
 * арифметических выражений. Еще ее иногда называют постфиксной нотацией.
 * В постфиксной нотации операнды расположены перед знаками операций.
 *
 * Пример 1:
 * 3 4 +
 * означает 3 + 4 и равно 7
 *
 * Пример 2:
 * 12 5 /
 * Так как деление целочисленное, то в результате получим 2
 *
 * Пример 3:
 * 10 2 4 * -
 * означает 10 - 2 * 4 и равно 2
 *
 * Разберем последний пример подробнее:
 * Знак * стоит сразу после чисел 2 и 4, значит к ним нужно применить операцию,
 * которую этот знак обозначает, то есть перемножить эти два числа. В результате
 * получим 8.
 *
 * После этого выражение приобретет вид:
 * 10 8 -
 *
 * Операцию «минус» нужно применить к двум идущим перед ней числам, то есть
 * 10 и 8. В итоге получаем 2.
 *
 * Рассмотрим алгоритм более подробно. Для его реализации будем использовать
 * стек.
 *
 * Для вычисления значения выражения, записанного в обратной польской нотации,
 * нужно считывать выражение слева направо и придерживаться следующих шагов:
 * 1. Обработка входного символа:
 *    - Если на вход подан операнд, он помещается на вершину стека.
 *    - Если на вход подан знак операции, то эта операция выполняется над
 *      требуемым количеством значений, взятых из стека в порядке добавления.
 *      Результат выполненной операции помещается на вершину стека.
 * 2. Если входной набор символов обработан не полностью, перейти к шагу 1.
 * 3. После полной обработки входного набора символов результат вычисления
 *    выражения находится в вершине стека. Если в стеке осталось несколько
 *    чисел, то надо вывести только верхний элемент.
 *
 * Замечание про отрицательные числа и деление: в этой задаче под делением
 * понимается математическое целочисленное деление. Это значит, что округление
 * всегда происходит вниз. А именно: если a / b = c, то b ⋅ c - это наибольшее
 * число, которое не превосходит a и одновременно делится без остатка на b.
 *
 * Например, -1 / 3 = -1. Будьте осторожны: в C++, Java и Go, например, деление
 * чисел работает иначе. В текущей задаче гарантируется, что деления на
 * отрицательное число нет.
 *
 * Формат ввода
 * В единственной строке дано выражение, записанное в обратной польской нотации.
 * Числа и арифметические операции записаны через пробел. На вход могут
 * подаваться операции: +, -, *, / и числа, по модулю не превосходящие 10000.
 * Гарантируется, что значение промежуточных выражений в тестовых данных
 * по модулю не больше 50000.
 *
 * Формат вывода
 * Выведите единственное число - значение выражения.
 *
 * Отчет: https://contest.yandex.ru/contest/22781/run-report/107338540/
 */

const { run, readLine } = require('../../lib/io');

const OPERATORS = new Set(['+', '-', '*', '/']);

/**
 * Стек на массиве без использования встроенных push и pop.
 *
 * Вершиной служит конец массива - единственное место, где вставка и удаление
 * выполняются без сдвига элементов, то есть за O(1).
 */
class Stack {
  constructor() {
    this.items = [];
  }

  /**
   * Кладет элемент на вершину стека.
   *
   * Время: O(1) амортизированно.
   *
   * @param {*} item Добавляемое значение.
   * @returns {void}
   */
  push(item) {
    this.items[this.items.length] = item;
  }

  /**
   * Снимает элемент с вершины стека.
   *
   * Время: O(1).
   *
   * @returns {*} Снятое значение либо undefined, если стек пуст.
   */
  pop() {
    if (this.items.length === 0) {
      return undefined;
    }

    const lastItem = this.items[this.items.length - 1];

    this.items.length = this.items.length - 1;

    return lastItem;
  }

  /**
   * Возвращает элемент на вершине, не снимая его.
   *
   * Время: O(1).
   *
   * @returns {*} Значение на вершине либо undefined, если стек пуст.
   */
  peek() {
    if (this.items.length === 0) {
      return undefined;
    }

    return this.items[this.items.length - 1];
  }

  /**
   * Возвращает количество элементов в стеке.
   *
   * Время: O(1).
   *
   * @returns {number} Количество элементов.
   */
  size() {
    return this.items.length;
  }
}

/**
 * Вычисляет значение выражения в обратной польской нотации.
 *
 * Операнды накапливаются на стеке; знак операции снимает два верхних значения
 * и кладет обратно результат. Порядок снятия обратен порядку записи, поэтому
 * первым снимается правый операнд - для вычитания и деления это существенно.
 *
 * Время: O(n). Память: O(n).
 *
 * @param {string[]} tokens Числа и знаки операций в порядке следования.
 * @returns {number} Значение выражения.
 */
function evaluate(tokens) {
  const stack = new Stack();

  for (const token of tokens) {
    if (!OPERATORS.has(token)) {
      stack.push(Number(token));
      continue;
    }

    const rightOperand = stack.pop();
    const leftOperand = stack.pop();

    switch (token) {
      case '+':
        stack.push(leftOperand + rightOperand);
        break;
      case '-':
        stack.push(leftOperand - rightOperand);
        break;
      case '*':
        stack.push(leftOperand * rightOperand);
        break;
      case '/':
        // По условию деление целочисленное с округлением вниз, поэтому
        // Math.floor, а не отбрасывание дробной части Math.trunc
        stack.push(Math.floor(leftOperand / rightOperand));
        break;
    }
  }

  return stack.peek();
}

function solve() {
  const tokens = readLine().trim().split(/\s+/);

  process.stdout.write(`${evaluate(tokens)}`);
}

run(solve);
