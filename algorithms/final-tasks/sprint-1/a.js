/**
 * A. Ближайший ноль
 *
 * https://contest.yandex.ru/contest/22450/problems/A/
 *
 * Тимофей ищет место, чтобы построить себе дом. Улица, на которой он хочет
 * жить, имеет длину n, то есть состоит из n одинаковых идущих подряд участков.
 * Каждый участок либо пустой, либо на нем уже построен дом. Общительный Тимофей
 * не хочет жить далеко от других людей на этой улице. Поэтому ему важно для
 * каждого участка знать расстояние до ближайшего пустого участка. Если участок
 * пустой, эта величина будет равна нулю - расстояние до самого себя. Помогите
 * Тимофею посчитать искомые расстояния. Для этого у вас есть карта улицы. Дома
 * в городе Тимофея нумеровались в том порядке, в котором строились, поэтому их
 * номера на карте никак не упорядочены. Пустые участки обозначены нулями.
 *
 * Формат ввода
 * В первой строке дана длина улицы - n (1 ≤ n ≤ 10^6). В следующей строке
 * записаны n целых неотрицательных чисел - номера домов и обозначения пустых
 * участков на карте (нули). Гарантируется, что в последовательности есть хотя
 * бы один ноль. Номера домов (положительные числа) уникальны и не превосходят
 * 10^9.
 *
 * Формат вывода
 * Для каждого из участков выведите расстояние до ближайшего нуля. Числа
 * выводите в одну строку, разделяя их пробелами.
 */

const { run, readInt, readArray } = require('../../lib/io');

/**
 * Возвращает для каждого элемента массива расстояние до ближайшего нуля.
 *
 * Один проход выполняет сразу два просмотра: индекс i движется слева направо и
 * отслеживает последний встреченный ноль, индекс len - 1 - i движется справа
 * налево и делает то же самое в обратном направлении. Для каждой позиции
 * берется минимум из двух расстояний. К моменту завершения цикла каждая
 * позиция обработана обоими просмотрами.
 *
 * Время: O(n). Память: O(n).
 *
 * @param {number[]} numbers Номера домов; нули обозначают пустые участки.
 *   Гарантируется наличие хотя бы одного нуля.
 * @returns {number[]} Расстояния до ближайшего нуля.
 */
function getDistance(numbers) {
  const len = numbers.length;

  let leftIndex = -1;
  let rightIndex = -1;

  // fill заметно быстрее Array.from на массивах из 10^6 элементов
  const result = new Array(len).fill(Infinity);

  for (let i = 0; i < len; i++) {
    if (numbers[i] === 0) {
      leftIndex = i;
    }

    if (leftIndex !== -1) {
      result[i] = Math.min(result[i], Math.abs(i - leftIndex));
    }

    if (numbers[len - 1 - i] === 0) {
      rightIndex = len - 1 - i;
    }

    if (rightIndex !== -1) {
      result[len - 1 - i] = Math.min(
        result[len - 1 - i],
        Math.abs(len - 1 - i - rightIndex),
      );
    }
  }

  return result;
}

function solve() {
  const n = readInt();
  const numbers = readArray();
  process.stdout.write(`${getDistance(numbers).join(' ')}`);
}

run(solve);
