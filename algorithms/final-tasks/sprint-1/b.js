/**
 * B. Ловкость рук
 *
 * https://contest.yandex.ru/contest/22450/problems/B/
 *
 * Игра «Тренажер для скоростной печати» представляет собой поле 4x4 из клавиш,
 * на которых - либо точка, либо цифра от одного до девяти. Суть игры следующая:
 * каждый раунд на поле появляется комбинация цифр и точек. В момент времени t
 * игрок должен одновременно нажать на все клавиши, где есть цифра t.
 *
 * Если в момент t нажаты все нужные клавиши, игроки получают один балл. Если
 * клавиш с цифрой t на поле нет, победное очко не начисляется.
 *
 * Два игрока в один момент могут нажать на k клавиш каждый. Найдите число
 * баллов, которое смогут заработать Гоша и Тимофей, если будут нажимать на
 * клавиши вдвоем. Рассмотрим пример 1, в котором k=3.
 *
 * 3
 * 1231
 * 2..2
 * 2..2
 * 2..2
 *
 * Допустим, t=1. В таком случае один игрок должен нажать на две кнопки
 * с цифрой 1. Чтобы узнать, сколько клавиш нажмут два игрока, воспользуемся
 * формулой: k*2. Получается, что вместе мальчики нажмут на шесть клавиш
 * и получат победное очко.
 *
 * Когда t=2, двум игрокам необходимо нажать на семь кнопок одновременно. Но это
 * не под силу ребятам: каждый может нажать только по три кнопки. Победное очко
 * не начисляется.
 *
 * При t=3, каждому игроку нужно нажать на одну кнопку. Успех! Теперь на счету
 * Гоши и Тимофея целых два победных очка.
 *
 * Других цифр на поле нет. Поэтому в следующих раундах, где t=4...t=9,
 * победные очки начисляться не будут. Таким образом, Гоша и Тимофей заработают
 * два балла.
 *
 * Найдите число баллов, которое смогут заработать Гоша и Тимофей, если будут
 * нажимать на клавиши вдвоем.
 *
 * Формат ввода
 * В первой строке дано целое число k (1 ≤ k ≤ 5).
 * В четырех следующих строках задан вид тренажера - по 4 символа в каждой
 * строке. Каждый символ – либо точка, либо цифра от 1 до 9. Символы одной
 * строки идут подряд и не разделены пробелами.
 *
 * Формат вывода
 * Выведите единственное число - максимальное количество баллов, которое смогут
 * набрать Гоша и Тимофей.
 */

const { run, readInt, readLine } = require('../../lib/io');

const MATRIX_ROWS = 4;
const MAX_TIME = 9;
const DIGIT = /^\d$/;

/**
 * Возвращает количество баллов, набранных двумя игроками.
 *
 * Балл начисляется за момент времени t, если на поле есть хотя бы одна клавиша
 * с цифрой t и общее их количество не превосходит 2k - числа клавиш, которые
 * два игрока могут нажать одновременно.
 *
 * Время: O(m + T), где m - число клавиш, T - число моментов времени.
 * Память: O(T).
 *
 * @param {number} k Количество клавиш, которое нажимает один игрок.
 * @param {number[]} matrix Цифры на клавишах поля одним списком.
 * @returns {number} Количество набранных баллов.
 */
function getPoints(k, matrix) {
  const countMap = new Map();

  for (let i = 0, len = matrix.length; i < len; i++) {
    const num = matrix[i];
    const curVal = countMap.get(num) || 0;

    countMap.set(num, curVal + 1);
  }

  let result = 0;

  for (let i = 1; i <= MAX_TIME; i++) {
    const count = countMap.get(i) || 0;

    if (count > 0 && count <= k * 2) {
      result++;
    }
  }

  return result;
}

function solve() {
  const k = readInt();
  const matrix = readDigitField(MATRIX_ROWS);

  process.stdout.write(`${getPoints(k, matrix)}`);
}

/**
 * Читает очередную строку поля и возвращает записанные в ней цифры.
 *
 * Символы поля идут подряд без разделителей, а точки обозначают пустые
 * клавиши, поэтому строка разбирается посимвольно с отбрасыванием всего,
 * что не является цифрой. Общий readArray здесь не подходит: он рассчитан
 * на числа, разделенные пробелами.
 *
 * @returns {number[]} Цифры строки в порядке следования.
 */
function readDigits() {
  return readLine()
    .trim()
    .split('')
    .filter((char) => DIGIT.test(char))
    .map(Number);
}

/**
 * Читает поле тренажера и возвращает все его цифры одним списком.
 *
 * Расположение цифр по строкам для решения не важно - существенно только
 * количество вхождений каждой цифры, поэтому поле разворачивается в плоский
 * список.
 *
 * @param {number} rowsCount Количество строк поля.
 * @returns {number[]} Цифры поля одним списком.
 */
function readDigitField(rowsCount) {
  let digits = [];

  for (let i = 0; i < rowsCount; i++) {
    digits = digits.concat(readDigits());
  }

  return digits;
}

run(solve);
