/**
 * Меняет местами два элемента массива.
 *
 * @param {*[]} array Массив; изменяется на месте.
 * @param {number} x Индекс первого элемента.
 * @param {number} y Индекс второго элемента.
 * @returns {void}
 */
function swap(array, x, y) {
  [array[x], array[y]] = [array[y], array[x]];
}

/**
 * Компаратор участников: возвращает true, если первый должен идти раньше.
 *
 * Порядок сравнения задан условием: больше решенных задач, при равенстве -
 * меньший штраф, при равенстве - логин раньше в лексикографическом порядке.
 * Логины уникальны, поэтому сравнение всегда разрешается и порядок строгий.
 *
 * Время: O(1) сверх сравнения логинов.
 *
 * @param {{login: string, solved: number, penalty: number}} first Первый участник.
 * @param {{login: string, solved: number, penalty: number}} second Второй участник.
 * @returns {boolean} true, если first должен идти раньше second.
 */
function compare(first, second) {
  if (first.solved !== second.solved) {
    return first.solved > second.solved;
  }

  if (first.penalty !== second.penalty) {
    return first.penalty < second.penalty;
  }

  return first.login < second.login;
}

/**
 * Переупорядочивает отрезок массива относительно опорного элемента.
 *
 * Два указателя идут навстречу: левый останавливается на элементе, который не
 * должен идти раньше опорного, правый - на элементе, перед которым опорный идти
 * не должен. Найденная пара нарушает порядок и меняется местами.
 *
 * Возвращаемый индекс всегда строго больше left и не больше right, поэтому обе
 * части строго короче исходного отрезка.
 *
 * Время: O(right - left). Память: O(1).
 *
 * @param {*[]} array Массив; изменяется на месте.
 * @param {*} pivot Опорный элемент.
 * @param {number} left Левая граница отрезка, включительно.
 * @param {number} right Правая граница отрезка, включительно.
 * @returns {number} Индекс начала правой части.
 */
function partition(array, pivot, left, right) {
  while (left <= right) {
    while (compare(array[left], pivot)) {
      left++;
    }

    while (compare(pivot, array[right])) {
      right--;
    }

    if (left <= right) {
      swap(array, left, right);
      left++;
      right--;
    }
  }

  return left;
}

/**
 * Сортирует массив быстрой сортировкой на месте, без O(n) дополнительной памяти.
 *
 * Рекурсия выполняется только для меньшей из двух частей, большая
 * обрабатывается продолжением цикла в том же вызове. Это ограничивает глубину
 * стека величиной O(log n) при любых входных данных: размер задачи, уходящей в
 * рекурсию, каждый раз уменьшается минимум вдвое.
 *
 * Ограничение существенно. При рекурсии в обе части глубина зависит от качества
 * разбиений, и на входе вида «возрастание, затем убывание» опорный элемент по
 * середине отрезка каждый раз оказывается близок к максимуму. Разбиения
 * вырождаются, глубина достигает O(n), и при n = 100000 из условия сортировка
 * падает с ошибкой RangeError: Maximum call stack size exceeded.
 *
 * Время: O(n log n) в среднем, O(n²) в худшем случае. Память: O(log n).
 *
 * @param {*[]} array Сортируемый массив; изменяется на месте.
 * @param {number} left Левая граница сортируемого отрезка, включительно.
 * @param {number} right Правая граница сортируемого отрезка, включительно.
 * @returns {void}
 */
function quicksort(array, left = 0, right = array.length - 1) {
  let low = left;
  let high = right;

  while (low < high) {
    const pivot = array[low + Math.floor((high - low) / 2)];
    const index = partition(array, pivot, low, high);

    if (index - 1 - low < high - index) {
      quicksort(array, low, index - 1);
      low = index;
    } else {
      quicksort(array, index, high);
      high = index - 1;
    }
  }
}
// =============================================================================

run(solve);
