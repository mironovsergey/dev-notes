/**
 * B. Одинаковые суммы
 *
 * https://contest.yandex.ru/contest/25597/problems/B/
 *
 * На Алгосах устроили турнир по настольному теннису. Гоша выиграл n партий,
 * получив при этом некоторое количество очков за каждую из них.
 *
 * Гоше стало интересно, можно ли разбить все заработанные им во время турнира
 * очки на две части так, чтобы сумма в них была одинаковой.
 *
 * Формат ввода
 * В первой строке записано целое число n (0 ≤ n ≤ 300) - количество выигранных
 * партий. Во второй строке через пробел записано n целых неотрицательных чисел,
 * каждое из которых не превосходит 300 - заработанные в партиях очки.
 *
 * Формат вывода
 * Нужно вывести True, если произвести такое разбиение возможно, иначе - False
 *
 * Отчет: https://contest.yandex.ru/contest/25597/run-report/116458503/
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const n = readInt();
  const points = readLine().split(' ').map(Number);

  process.stdout.write(`${canSplitEqually(points) ? 'True' : 'False'}`);
}

/**
 * Проверяет, можно ли разделить числа на две части с равными суммами.
 *
 * Задача сводится к рюкзаку: набрать подмножество с суммой ровно в половину
 * общей. Состояние dp[j] - достижима ли сумма j; вместо максимума в переходе
 * стоит логическое «или».
 *
 * Нечетная общая сумма отсекается сразу: половина не была бы целой.
 *
 * Цикл по суммам идет в порядке убывания. Это принципиально: dp[j - num]
 * должно содержать значение, еще не учитывающее текущее число, иначе одно
 * число можно было бы использовать несколько раз, и ответ был бы неверным.
 *
 * Время: O(n · S), где S - половина суммы. Память: O(S).
 *
 * @param {number[]} nums Целые числа.
 * @returns {boolean} true, если разбиение на две равные части возможно.
 */
function canSplitEqually(nums) {
  // Сумму всех чисел в массиве
  const totalSum = nums.reduce((acc, curr) => acc + curr, 0);

  // Если общая сумма нечетная, то невозможно разделить ее на две равные части
  if (totalSum % 2 !== 0) {
    return false;
  }

  // Целевая сумма, равная половине общей суммы
  const halfSum = totalSum / 2;

  // Массив динамического программирования
  // dp[i] будет True, если можно получить сумму i, используя подмножество
  // чисел из массива
  const dp = Array(halfSum + 1).fill(false);

  // Начальное условие: сумма 0 всегда достижима (пустой массив)
  dp[0] = true;

  // Итерация по каждому числу в массиве
  for (const num of nums) {
    // Итерация по целевой сумме от halfSum до текущего числа (в обратном
    // порядке)
    for (let j = halfSum; j >= num; j--) {
      // Обновление dp[j], если сумма j может быть достигнута добавлением
      // текущего числа num
      dp[j] = dp[j] || dp[j - num];
    }
  }

  return dp[halfSum];
}

run(solve);
