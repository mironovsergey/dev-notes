/**
 * A. Расстояние по Левенштейну
 *
 * https://contest.yandex.ru/contest/25597/problems/A/
 *
 * Расстоянием Левенштейна между двумя строками s и t называется количество
 * атомарных изменений, с помощью которых можно одну строку превратить в другую.
 * Под атомарными изменениями подразумеваются: удаление одного символа, вставка
 * одного символа, замена одного символа на другой.
 *
 * Найдите расстояние Левенштейна для предложенной пары строк.
 *
 * Выведите единственное число - расстояние между строками.
 *
 * Формат ввода
 * В первой строке дана строка s, во второй - строка t. Длины обеих строк
 * не превосходят 1000. Строки состоят из маленьких латинских букв.
 *
 * Отчет: https://contest.yandex.ru/contest/25597/run-report/116458277/
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  // Исходная строка, от которой начинается преобразование
  const source = readLine();

  // Целевая строка, к которой необходимо прийти в результате преобразований
  const target = readLine();

  process.stdout.write(`${levenshteinDistance(source, target)}`);
}

/**
 * Вычисляет расстояние Левенштейна между двумя строками
 *
 * @param {string} s Исходная строка
 * @param {string} t Целевая строка
 * @returns {number} Расстояние Левенштейна между строками s и t
 */
/**
 * Возвращает расстояние Левенштейна между двумя строками.
 *
 * Состояние dp[i][j] - минимальное число операций, превращающих первые i
 * символов s в первые j символов t. Переход разбирает случаи по последней
 * операции: удаление, вставка или замена.
 *
 * База нетривиальна, в отличие от большинства двумерных задач: dp[i][0] = i
 * означает «удалить все i символов», dp[0][j] = j - «вставить все j».
 *
 * Стоимость замены равна нулю при совпадении символов, поэтому отдельная
 * ветка для совпадения не нужна - минимум сам выберет диагональный переход.
 *
 * Время: O(|s| · |t|). Память: O(|s| · |t|).
 *
 * @param {string} s Исходная строка.
 * @param {string} t Целевая строка.
 * @returns {number} Минимальное число операций редактирования.
 */
function levenshteinDistance(s, t) {
  const m = s.length; // Длина исходной строки
  const n = t.length; // Длина целевой строки

  // Инициализация таблицы размером (m+1) x (n+1)
  const dp = Array.from({ length: m + 1 }, () => Array(n + 1).fill(0));

  // Заполнение первой строки таблицы
  for (let i = 0; i <= m; i++) {
    // Требуется i удалений для преобразования s[0...i-1] в пустую строку
    dp[i][0] = i;
  }

  // Заполнение первого столбца таблицы
  for (let j = 0; j <= n; j++) {
    // Требуется j вставок для преобразования пустой строки в t[0...j-1]
    dp[0][j] = j;
  }

  // Заполнение оставшихся ячеек таблицы
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      // Стоимость замены: 0 - если символы совпадают, 1 - если нет
      const substitutionCost = s[i - 1] === t[j - 1] ? 0 : 1;

      // Выбор минимальной стоимости среди удаления, вставки и замены
      dp[i][j] = Math.min(
        dp[i - 1][j] + 1, // Стоимость удаления
        dp[i][j - 1] + 1, // Стоимость вставки
        dp[i - 1][j - 1] + substitutionCost, // Стоимость замены
      );
    }
  }

  return dp[m][n];
}

run(solve);
