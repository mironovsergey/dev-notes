/**
 * Считывание массивов.
 * На первой строке указывается размер массива - число n, на второй -
 * перечисляются элементы массива через пробел.
 */

const { run, readInt, readArray } = require('../../lib/io');

function solve() {
  // Размер массива задан отдельной строкой; значение не требуется,
  // но строку нужно прочитать, чтобы сдвинуть позицию чтения
  readInt();
  const numbers = readArray();

  process.stdout.write(`${numbers.join(' ')}`);
}

run(solve);
