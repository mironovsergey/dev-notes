/**
 * A. Построить список смежности
 *
 * https://contest.yandex.ru/contest/25069/problems/A/
 *
 * Алла пошла на стажировку в студию графического дизайна, где ей дали такое
 * задание: для очень большого числа ориентированных графов преобразовать их
 * список ребер в список смежности. Чтобы побыстрее решить эту задачу, она
 * решила автоматизировать процесс.
 *
 * Помогите Алле написать программу, которая по списку ребер графа будет строить
 * его список смежности.
 *
 * Формат ввода
 * В первой строке дано число вершин n (1 ≤ n ≤ 100) и число ребер
 * m (1 ≤ m ≤ n(n-1)). В следующих m строках заданы ребра в виде
 * пар вершин (u,v), если ребро ведет от u к v.
 *
 * Формат вывода
 * Выведите информацию о ребрах, исходящих из каждой вершины.
 *
 * В строке i надо написать число ребер, исходящих из вершины i, а затем
 * перечислить вершины, в которые ведут эти ребра - в порядке возрастания
 * их номеров.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  // Чтение числа вершин (n) и числа ребер (m)
  const [n, m] = readLine()
    .trim()
    .split(' ')
    .map((val) => parseInt(val, 10));

  // Массив ребер графа
  const edges = [];

  // Чтение всех ребер
  for (let i = 1; i <= m; i++) {
    edges.push(
      readLine()
        .trim()
        .split(' ')
        .map((val) => parseInt(val, 10)),
    );
  }

  // Создание списка смежности
  const adjacencyList = createAdjacencyList(n, edges);

  // Вывод результата
  for (let i = 1; i <= n; i++) {
    process.stdout.write(
      `${adjacencyList[i].length} ${adjacencyList[i].join(' ')}\n`,
    );
  }
}

/**
 * Создает списки смежности ориентированного графа.
 *
 * Списки сортируются: условие требует выводить смежные вершины в порядке
 * возрастания номеров, а порядок ребер во входных данных произволен.
 *
 * Время: O(|V| + |E|·log|E|) из-за сортировки. Память: O(|V| + |E|).
 *
 * @param {number} n Число вершин графа.
 * @param {Array<[number, number]>} edges Ребра в виде пар [u, v].
 * @returns {number[][]} Списки смежности; элемент с индексом i содержит
 *   вершины, смежные с вершиной i, по возрастанию.
 */
function createAdjacencyList(n, edges) {
  // Создаем массив для списка смежности, инициализируем пустыми массивами
  const adjacencyList = Array.from({ length: n + 1 }, () => []);

  // Заполняем список смежности
  edges.forEach(([u, v]) => {
    adjacencyList[u].push(v);
  });

  // Сортируем списки смежности для каждой вершины
  for (let i = 1; i <= n; i++) {
    adjacencyList[i].sort((a, b) => a - b);
  }

  return adjacencyList;
}

run(solve);
