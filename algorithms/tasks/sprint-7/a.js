/**
 * A. Биржа
 *
 * https://contest.yandex.ru/contest/25596/problems/A/
 *
 * Рита хочет попробовать поиграть на бирже. Но для начала она решила
 * потренироваться на исторических данных.
 *
 * Даны стоимости акций в каждый из n дней. В течение дня цена акции не
 * меняется. Акции можно покупать и продавать, но только по одной штуке в день.
 * В один день нельзя совершать более одной операции (покупки или продажи).
 * Также на руках не может быть более одной акции в каждый момент времени.
 *
 * Помогите Рите выяснить, какую максимальную прибыль она могла бы получить.
 *
 * Формат ввода
 * В первой строке записано количество дней n - целое число в диапазоне от 0
 * до 10 000. Во второй строке через пробел записано n целых чисел в диапазоне
 * от 0 до 1000 - цены акций.
 *
 * Формат вывода
 * Выведите число, равное максимально возможной прибыли за эти дни.
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const n = readInt();
  const prices = readLine().split(' ').map(Number);

  process.stdout.write(`${getMaxProfit(prices)}`);
}

/**
 * Возвращает наибольшую суммарную прибыль от торговли по известным ценам.
 *
 * Покупать и продавать разрешено сколько угодно раз, поэтому оптимально забрать
 * каждый участок роста: любую последовательность сделок можно разбить на пары
 * соседних дней, а сумма положительных разностей - верхняя граница прибыли,
 * которая этой стратегией и достигается.
 *
 * Время: O(n). Память: O(1).
 *
 * @param {number[]} prices Цены по дням.
 * @returns {number} Наибольшая прибыль.
 */
function getMaxProfit(prices) {
  let maxProfit = 0;

  for (let i = 1; i < prices.length; i++) {
    if (prices[i] > prices[i - 1]) {
      maxProfit += prices[i] - prices[i - 1];
    }
  }

  return maxProfit;
}

run(solve);
