/**
 * I. Сложное поле с цветочками
 *
 * https://contest.yandex.ru/contest/25596/problems/I/
 *
 * Теперь черепашке Кондратине надо узнать не только, сколько цветочков она
 * может собрать, но и как ей построить свой маршрут для этого. Помогите ей!
 *
 * Напомним, что Кондратине надо дойти от левого нижнего до правого верхнего
 * угла, а передвигаться она умеет только вверх и вправо.
 *
 * Формат ввода
 * В первой строке даны размеры поля n и m (через пробел). Оба числа лежат
 * в диапазоне от 1 до 1000. В следующих n строках задано поле. Каждая строка
 * состоит из m символов 0 или 1 и завершается переводом строки. Если в клетке
 * записана единица, то в ней растет цветочек.
 *
 * Формат вывода
 * Выведите в первой строке максимальное количество цветочков, которое сможет
 * собрать Кондратина. Во второй строке выведите маршрут в виде
 * последовательности символов «U» и «R», где «U» означает передвижение вверх,
 * а «R» – передвижение вправо.
 *
 * Если возможных оптимальных путей несколько, то выведите любой.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const [n, m] = readLine().split(' ').map(Number); // Размеры поля
  const matrix = [];

  for (let i = 1; i <= n; i++) {
    matrix.push(readLine().split('').map(Number));
  }

  const maxFlowersAndPath = getMaxFlowersAndPath(n, m, matrix);

  process.stdout.write(`${maxFlowersAndPath.maxFlowers}\n`);
  process.stdout.write(`${maxFlowersAndPath.path}`);
}

/**
 * Возвращает наибольшее число цветочков и сам маршрут их сбора.
 *
 * Таблица заполняется так же, как в задаче H. Маршрут восстанавливается
 * обратным проходом от правого верхнего угла: в каждой клетке проверяется,
 * какой из двух соседей дал записанное значение. Буквы накапливаются от конца
 * маршрута к началу, поэтому результат разворачивается.
 *
 * Время: O(n·m). Память: O(n·m).
 *
 * @param {number} n Количество строк поля.
 * @param {number} m Количество столбцов поля.
 * @param {number[][]} matrix Поле: 1 - цветочек, 0 - пусто.
 * @returns {{maxFlowers: number, path: string}} Количество цветочков
 *   и маршрут из букв U (вверх) и R (вправо).
 */
function getMaxFlowersAndPath(n, m, matrix) {
  const dp = Array.from({ length: n }, () => Array(m).fill(0));

  dp[n - 1][0] = matrix[n - 1][0];

  for (let i = n - 2; i >= 0; i--) {
    dp[i][0] = dp[i + 1][0] + matrix[i][0];
  }

  for (let j = 1; j < m; j++) {
    dp[n - 1][j] = dp[n - 1][j - 1] + matrix[n - 1][j];
  }

  for (let i = n - 2; i >= 0; i--) {
    for (let j = 1; j < m; j++) {
      dp[i][j] = matrix[i][j] + Math.max(dp[i + 1][j], dp[i][j - 1]);
    }
  }

  let path = '';
  let i = 0;
  let j = m - 1;

  while (i < n - 1 || j > 0) {
    if (i < n - 1 && (j === 0 || dp[i + 1][j] >= dp[i][j - 1])) {
      path += 'U';
      i++;
    } else {
      path += 'R';
      j--;
    }
  }

  return {
    maxFlowers: dp[0][m - 1],
    path: path.split('').reverse().join(''),
  };
}

run(solve);
