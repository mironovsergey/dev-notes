/**
 * C. Золотая лихорадка
 *
 * https://contest.yandex.ru/contest/25596/problems/C/
 *
 * Гуляя по одному из островов Алгосского архипелага, Гоша набрел на пещеру,
 * в которой лежат кучи золотого песка. К счастью, у Гоши есть с собой рюкзак
 * грузоподъемностью до M килограмм, поэтому он может унести с собой какое-то
 * ограниченное количество золота.
 *
 * Всего золотых куч n штук, и все они разные. В куче под номером i содержится
 * mᵢ килограммов золотого песка, а стоимость одного килограмма - cᵢ алгосских
 * франков.
 *
 * Помогите Гоше наполнить рюкзак так, чтобы общая стоимость золотого песка
 * в пересчете на алгосские франки была максимальной.
 *
 * Формат ввода
 * В первой строке задано целое число M - грузоподъемность рюкзака Гоши
 * (0 ≤ M ≤ 10^8).
 *
 * Во второй строке дано количество куч с золотым песком - целое число n
 * (1 ≤ n ≤ 10^5).
 *
 * В каждой из следующих n строк описаны кучи: i-ая куча задается двумя целыми
 * числами cᵢ и mᵢ, записанными через пробел (1 ≤ cᵢ ≤ 10^7, 1 ≤ mᵢ ≤ 10^8).
 *
 * Формат вывода
 * Выведите единственное число - максимальную сумму (в алгосских франках),
 * которую Гоша сможет вынести из пещеры в своем рюкзаке.
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const m = readInt(); // Грузоподъемность рюкзака
  const n = readInt(); // Количество куч с золотым песком
  const piles = []; // Кучи золотого песка

  for (let i = 1; i <= n; i++) {
    piles.push(readLine().split(' ').map(Number));
  }

  process.stdout.write(`${getMaxGold(m, piles)}`);
}

/**
 * Возвращает наибольшую стоимость золотого песка, помещающегося в рюкзак.
 *
 * Песок делим, поэтому задача - дробный рюкзак, и жадность здесь оптимальна:
 * кучи перебираются по убыванию стоимости единицы массы, последняя берется
 * частично. Для неделимых предметов такой подход был бы неверен.
 *
 * Время: O(n·log n) на сортировку. Память: O(1) сверх сортировки.
 *
 * @param {number} capacity Грузоподъемность рюкзака.
 * @param {Array<[number, number]>} piles Кучи в виде [стоимость единицы, масса];
 *   массив сортируется.
 * @returns {number} Наибольшая суммарная стоимость.
 */
function getMaxGold(capacity, piles) {
  let total = 0;

  piles.sort((a, b) => b[0] - a[0]);

  for (let i = 0; i < piles.length; i++) {
    const [cost, mass] = piles[i];

    if (capacity === 0) {
      break;
    }

    const goldToTake = Math.min(mass, capacity);

    total += goldToTake * cost;
    capacity -= goldToTake;
  }

  return total;
}

run(solve);
