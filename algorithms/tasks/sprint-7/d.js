/**
 * D. Числа Фибоначчи для взрослых
 *
 * https://contest.yandex.ru/contest/25596/problems/D/
 *
 * Гоша практикуется в динамическом программировании - он хочет быстро считать
 * числа Фибоначчи.
 *
 * Помогите Гоше решить эту задачу.
 *
 * Формат ввода
 * В единственной строке дано целое число n (0 ≤ n ≤ 10^6).
 *
 * Формат вывода
 * Вычислите значение Fₙ по модулю 10^9 + 7 и выведите его.
 */

const { run, readInt } = require('../../lib/io');

function solve() {
  const n = readInt();

  process.stdout.write(`${fibonacci(n)}`);
}

const MODULO = 10 ** 9 + 7;

/**
 * Возвращает n-е число Фибоначчи по модулю 10^9 + 7.
 *
 * Используется соглашение F₀ = 0, F₁ = 1. Хранятся только два последних
 * значения: для вычисления очередного больше ничего не нужно, поэтому таблица
 * на 10^6 элементов не требуется.
 *
 * Остаток берется на каждом шаге: без него значения выходят за пределы точного
 * представления целых чисел уже около n = 79.
 *
 * Время: O(n). Память: O(1).
 *
 * @param {number} n Номер числа, 0 <= n <= 10^6.
 * @returns {number} Значение Fₙ по модулю 10^9 + 7.
 */
function fibonacci(n) {
  if (n <= 1) {
    return n;
  }

  // Инициализация задает F₀ и F₁; первая же итерация вычисляет F₂
  let previous = 0;
  let current = 1;

  for (let i = 2; i <= n; i++) {
    const next = (previous + current) % MODULO;

    previous = current;
    current = next;
  }

  return current;
}

run(solve);
