/**
 * G. Банкомат
 *
 * https://contest.yandex.ru/contest/25596/problems/G/
 *
 * Тимофей пошел снять деньги в банкомат. Ему нужно m франков. В банкомате
 * в бесконечном количестве имеются купюры различных достоинств. Всего различных
 * достоинств n. Купюр каждого достоинства можно взять бесконечно много. Нужно
 * определить число способов, которыми Тимофей сможет набрать нужную сумму.
 *
 * Пример 1
 * 5 франков можно набрать следующими способами:
 * 1 + 1 + 1 + 1 + 1
 * 1 + 1 + 1 + 2
 * 1 + 1 + 3
 * 1 + 2 + 2
 * 2 + 3
 *
 * Пример 2
 * Во втором примере всего две возможности набрать в сумме 3:
 * 1 + 2
 * 1 + 1 + 1
 *
 * Пример 3
 * Набрать ровно 8 франков купюрами по 5 франков невозможно. Ответ равен нулю.
 *
 * Формат ввода
 * В первой строке записано целое число m - сумма, которую нужно набрать.
 * Во второй строке n - количество монет в банкомате. Оба числа не превосходят
 * 300. Далее в третьей строке записано n уникальных натуральных чисел, каждое
 * в диапазоне от 1 до 1000 - достоинства купюр.
 *
 * Формат вывода
 * Нужно вывести число способов, которым Тимофей сможет набрать нужную сумму.
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const m = readInt(); // Сумма, которую нужно набрать
  const n = readInt(); // Количество монет в банкомате
  const coins = readLine().split(' ').map(Number); // Достоинства купюр

  process.stdout.write(`${coinChange(m, coins)}`);
}

/**
 * Возвращает количество способов набрать сумму купюрами заданных достоинств.
 *
 * Состояние dp[i] - число способов набрать сумму i. База dp[0] = 1: пустой
 * набор дает нулевую сумму единственным способом.
 *
 * Порядок вложенности циклов здесь определяет саму задачу. Внешний цикл идет
 * по купюрам: тогда каждый набор учитывается один раз независимо от порядка
 * купюр в нем, то есть считаются сочетания - как и требует условие. При
 * обратном порядке циклов наборы 1 + 2 и 2 + 1 считались бы разными, и ответ
 * оказался бы завышенным.
 *
 * Время: O(amount · n). Память: O(amount).
 *
 * @param {number} amount Требуемая сумма.
 * @param {number[]} coins Достоинства купюр.
 * @returns {number} Количество способов набрать сумму.
 */
function coinChange(amount, coins) {
  const dp = new Array(amount + 1).fill(0);

  dp[0] = 1;

  for (let coin of coins) {
    for (let i = coin; i <= amount; i++) {
      dp[i] += dp[i - coin];
    }
  }

  return dp[amount];
}

run(solve);
