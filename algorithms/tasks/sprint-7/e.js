/**
 * E. Алла на Алгосах
 *
 * https://contest.yandex.ru/contest/25596/problems/E/
 *
 * Алла хочет купить дом на Алгосах. Для этого ей надо много наличных, которые
 * она собирается получить в банкомате. Банкомат приличный, поэтому в нем есть
 * бесконечно много банкнот каждого номинала. Всего номиналов k штук. Дом мечты
 * Аллы стоит x франков.
 *
 * Найдите минимальное количество банкнот, которые в сумме дадут x франков. Если
 * в набор входит несколько банкнот одинакового номинала, то учитывать надо их
 * все.
 *
 * Например, если необходимо набрать 15 франков, а в банкомате купюры по 5
 * франков, то минимальное число купюр - 3.
 *
 * Формат ввода
 * В первой строке дана сумма, которую хочет получить Алла - натуральное число x
 * (1 ≤ x ≤ 10^4). Во второй строке дано число различных номиналов k. В третьей
 * строке даны k чисел (1 ≤ k ≤ 1000) - номиналы купюр. Все номиналы лежат
 * в диапазоне от 1 до 10^4. Номиналы купюр могут повторяться.
 *
 * Формат вывода
 * Выведите единственное число - минимальное количество купюр, которыми можно
 * набрать x франков. Если нельзя набрать в точности x франков, то выведите -1.
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const x = readInt(); // Требуемая сумма
  const k = readInt(); // Количество различных номиналов банкнот
  const coins = readLine().split(' ').map(Number); // Номиналы банкнот

  process.stdout.write(`${minCoins(x, coins)}`);
}

/**
 * Возвращает минимальное количество купюр, дающих в сумме заданную величину.
 *
 * Неограниченный рюкзак на минимум. Состояние dp[i] - минимальное число купюр
 * на сумму i; переход перебирает, какой была последняя купюра.
 *
 * Начальное значение amount + 1 играет роль бесконечности: набрать сумму
 * большим числом купюр, чем сама сумма, невозможно даже купюрами номинала 1,
 * поэтому такое значение заведомо недостижимо и означает «сумма не набирается».
 *
 * Время: O(amount · k). Память: O(amount).
 *
 * @param {number} amount Требуемая сумма.
 * @param {number[]} coins Номиналы купюр; могут повторяться.
 * @returns {number} Минимальное число купюр либо -1, если сумма недостижима.
 */
function minCoins(amount, coins) {
  const dp = Array(amount + 1).fill(amount + 1);

  dp[0] = 0;

  for (let i = 1; i <= amount; i++) {
    for (const coin of coins) {
      if (i >= coin) {
        dp[i] = Math.min(dp[i], dp[i - coin] + 1);
      }
    }
  }

  return dp[amount] > amount ? -1 : dp[amount];
}

run(solve);
