/**
 * H. Поле с цветочками
 *
 * https://contest.yandex.ru/contest/25596/problems/H/
 *
 * Черепаха Кондратина путешествует по клетчатому полю из n строк и m столбцов.
 * В каждой клетке либо растет цветочек, либо не растет. Кондратине надо
 * добраться из левого нижнего в правый верхний угол и собрать как можно больше
 * цветочков.
 *
 * Помогите ей с этой сложной задачей и определите, какое наибольшее число
 * цветочков она сможет собрать при условии, что Кондратина умеет передвигаться
 * только на одну клетку вверх или на одну клетку вправо за ход.
 *
 * Формат ввода
 * В первой строке даны размеры поля n и m (через пробел). Оба числа лежат
 * в диапазоне от 1 до 1000. В следующих n строках задано поле. Каждая строка
 * состоит из m символов 0 или 1, записанных подряд без пробелов, и завершается
 * переводом строки. Если в клетке записана единица, то в ней растет цветочек.
 *
 * Формат вывода
 * Выведите единственное число - максимальное количество цветочков, которое
 * сможет собрать Кондратина.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const [n, m] = readLine().split(' ').map(Number); // Размеры поля
  const matrix = [];

  for (let i = 1; i <= n; i++) {
    matrix.push(readLine().split('').map(Number));
  }

  process.stdout.write(`${getMaxFlowers(n, m, matrix)}`);
}

/**
 * Возвращает наибольшее число цветочков на пути из левого нижнего угла
 * в правый верхний при ходах только вверх и вправо.
 *
 * Состояние dp[i][j] - наибольшее число цветочков на пути из старта в клетку
 * (i, j). Переход разбирает случаи по последнему ходу: в клетку приходят
 * снизу, из (i+1, j), либо слева, из (i, j-1).
 *
 * Строки заполняются снизу вверх, а внутри строки слева направо - именно
 * в таком порядке обе клетки, на которые ссылается переход, уже вычислены.
 *
 * Время: O(n·m). Память: O(n·m).
 *
 * @param {number} n Количество строк поля.
 * @param {number} m Количество столбцов поля.
 * @param {number[][]} matrix Поле: 1 - цветочек, 0 - пусто.
 * @returns {number} Наибольшее количество собранных цветочков.
 */
function getMaxFlowers(n, m, matrix) {
  const dp = Array.from({ length: n }, () => Array(m).fill(0));

  dp[n - 1][0] = matrix[n - 1][0];

  for (let i = n - 2; i >= 0; i--) {
    dp[i][0] = dp[i + 1][0] + matrix[i][0];
  }

  for (let j = 1; j < m; j++) {
    dp[n - 1][j] = dp[n - 1][j - 1] + matrix[n - 1][j];
  }

  for (let i = n - 2; i >= 0; i--) {
    for (let j = 1; j < m; j++) {
      dp[i][j] = Math.max(dp[i + 1][j], dp[i][j - 1]) + matrix[i][j];
    }
  }

  return dp[0][m - 1];
}

run(solve);
