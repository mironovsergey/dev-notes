/**
 * F. Прыжки по лестнице
 *
 * https://contest.yandex.ru/contest/25596/problems/F/
 *
 * Алла хочет доказать, что она умеет прыгать вверх по лестнице быстрее всех.
 * На этот раз соревнования будут проходить на специальной прыгательной
 * лестнице. С каждой ее ступеньки можно прыгнуть вверх на любое расстояние
 * от 1 до k. Число k придумывает Алла.
 *
 * Гоша не хочет проиграть, поэтому просит вас посчитать количество способов
 * допрыгать от первой ступеньки до n-й. Изначально все стоят на первой
 * ступеньке.
 *
 * Формат ввода
 * В единственной строке даны два числа - n и k (1 ≤ n ≤ 1000, 1 ≤ k ≤ n).
 *
 * Формат вывода
 * Выведите количество способов по модулю 10^9 + 7.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const [n, k] = readLine().split(' ').map(Number);

  process.stdout.write(`${countWays(n, k)}`);
}

/**
 * Возвращает количество способов допрыгать с первой ступеньки до n-й
 * прыжками длиной от 1 до k.
 *
 * Состояние dp[i] - количество способов оказаться на ступеньке i. Переход
 * разбирает случаи по последнему прыжку: он был с одной из ступенек
 * i-1, …, i-k. Эти множества способов не пересекаются, поэтому количества
 * складываются.
 *
 * База dp[1] = 1, а не dp[0]: по условию отсчет начинается с первой ступеньки,
 * на которой все стоят изначально.
 *
 * Ответ берется по модулю: число способов растет экспоненциально и уже при
 * умеренных n выходит за пределы точного представления целых чисел.
 *
 * Время: O(n·k). Память: O(n).
 *
 * @param {number} n Номер целевой ступеньки.
 * @param {number} k Наибольшая длина прыжка.
 * @returns {number} Количество способов по модулю 10^9 + 7.
 */
function countWays(n, k) {
  const mod = 10 ** 9 + 7;
  const dp = Array(n + 1).fill(0);

  dp[1] = 1;

  for (let i = 2; i <= n; i++) {
    for (let j = 1; j <= k; j++) {
      if (i - j >= 1) {
        dp[i] = (dp[i] + dp[i - j]) % mod;
      }
    }
  }

  return dp[n];
}

run(solve);
