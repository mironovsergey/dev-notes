/**
 * E. Самое длинное слово
 *
 * https://github.com/Yandex-Practicum/algorithms-templates/blob/main/js/sprint1_nonfinals/e.js
 * https://contest.yandex.ru/contest/22449/problems/E/
 *
 * Чтобы подготовиться к семинару, Гоше надо прочитать статью по эффективному
 * менеджменту. Так как Гоша хочет спланировать день заранее, ему необходимо
 * оценить сложность статьи. Он придумал такой метод оценки: берется случайное
 * предложение из текста и в нем ищется самое длинное слово. Его длина и будет
 * условной сложностью статьи.
 *
 * Помогите Гоше справиться с этой задачей.
 *
 * Формат ввода
 * В первой строке дана длина текста L (1 ≤ L ≤ 10^5). В следующей строке
 * записан текст, состоящий из строчных латинских букв и пробелов. Слово -
 * последовательность букв, не разделенных пробелами. Пробелы могут стоять
 * в самом начале строки и в самом ее конце. Текст заканчивается переносом
 * строки, этот символ не включается в число остальных L символов.
 *
 * Формат вывода
 * В первой строке выведите самое длинное слово. Во второй строке выведите его
 * длину. Если подходящих слов несколько, выведите то, которое встречается
 * раньше.
 */

const { run, readInt, readLine } = require('../../lib/io');

/**
 * Возвращает самое длинное слово строки.
 *
 * Сравнение строгое, поэтому при равной длине сохраняется слово,
 * встретившееся раньше.
 *
 * Время: O(L), где L - длина строки. Память: O(L) на массив слов.
 *
 * @param {string} line Строка из строчных латинских букв и пробелов.
 * @returns {string} Самое длинное слово либо пустая строка, если слов нет.
 */
function getLongestWord(line) {
  const words = line.split(' ');

  let maxLength = 0;
  let longestWord = '';

  for (let i = 0; i < words.length; i++) {
    if (words[i].length > maxLength) {
      maxLength = words[i].length;
      longestWord = words[i];
    }
  }

  return longestWord;
}

function solve() {
  // Длина текста задана условием, но для решения не требуется:
  // строка читается целиком
  readInt();
  const line = readLine();
  const longestWord = getLongestWord(line);
  process.stdout.write(`${longestWord}`);
  process.stdout.write('\n');
  process.stdout.write(`${longestWord.length}`);
}

run(solve);
