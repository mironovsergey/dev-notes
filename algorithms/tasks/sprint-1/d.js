/**
 * D. Хаотичность погоды
 *
 * https://github.com/Yandex-Practicum/algorithms-templates/blob/main/js/sprint1_nonfinals/d.js
 * https://contest.yandex.ru/contest/22449/problems/D/
 *
 * Метеорологическая служба вашего города решила исследовать погоду новым
 * способом.
 * - Под температурой воздуха в конкретный день будем понимать максимальную
 *   температуру в этот день.
 * - Под хаотичностью погоды за n дней служба понимает количество дней,
 *   в которые температура строго больше, чем в день до (если такой существует)
 *   и в день после текущего (если такой существует). Например, если за 5 дней
 *   максимальная температура воздуха составляла [1, 2, 5, 4, 8] градусов,
 *   то хаотичность за этот период равна 2: в 3-й и 5-й дни выполнялись
 *   описанные условия.
 *
 * Определите по ежедневным показаниям температуры хаотичность погоды за этот
 * период.
 *
 * Заметим, что если число показаний n=1, то единственный день будет хаотичным.
 *
 * Формат ввода
 * В первой строке дано число n –- длина периода измерений в днях, 1 ≤ n ≤ 10^5.
 * Во второй строке даны n целых чисел – значения температуры в каждый из
 * n дней. Значения температуры не превосходят 273 по модулю.
 *
 * Формат вывода
 * Выведите единственное число - хаотичность за данный период.
 */

const { run, readInt, readArray } = require('../../lib/io');

/**
 * Возвращает хаотичность погоды - количество дней, в которые температура
 * строго выше, чем в соседние дни.
 *
 * Отсутствующий сосед на границе периода заменяется на -Infinity: такой сосед
 * никогда не мешает дню быть хаотичным. Это избавляет от отдельных ветвей для
 * первого и последнего дня и автоматически дает ответ 1 для периода из
 * одного дня.
 *
 * Время: O(n). Память: O(1).
 *
 * @param {number[]} temperatures Температуры по дням периода.
 * @returns {number} Количество хаотичных дней.
 */
function getWeatherRandomness(temperatures) {
  const length = temperatures.length;
  let result = 0;

  for (let i = 0; i < length; i++) {
    const previous = i > 0 ? temperatures[i - 1] : -Infinity;
    const next = i < length - 1 ? temperatures[i + 1] : -Infinity;

    if (temperatures[i] > previous && temperatures[i] > next) {
      result++;
    }
  }

  return result;
}

function solve() {
  const n = readInt();
  const temperatures = readArray();
  process.stdout.write(`${getWeatherRandomness(temperatures)}`);
}

run(solve);
