/**
 * J. Факторизация
 *
 * https://github.com/Yandex-Practicum/algorithms-templates/blob/main/js/sprint1_nonfinals/j.js
 * https://contest.yandex.ru/contest/22449/problems/J/
 *
 * Основная теорема арифметики говорит: любое число раскладывается на
 * произведение простых множителей единственным образом, с точностью до их
 * перестановки. Например:
 * - Число 8 можно представить как 2 × 2 × 2.
 * - Число 50 – как 2 × 5 × 5 (или 5 × 5 × 2, или 5 × 2 × 5). Три варианта
 *   отличаются лишь порядком следования множителей.
 *
 * Разложение числа на простые множители называется факторизацией числа.
 *
 * Напишите программу, которая производит факторизацию переданного числа.
 *
 * Формат ввода
 * В единственной строке дано число n (2 ≤ n ≤ 10^9), которое нужно
 * факторизовать.
 *
 * Формат вывода
 * Выведите в порядке неубывания простые множители, на которые раскладывается
 * число n.
 */

const { run, readInt } = require('../../lib/io');

/**
 * Раскладывает число на простые множители.
 *
 * Время: O(√n). Память: O(log n) на список множителей.
 *
 * @param {number} number Раскладываемое число, number >= 2.
 * @returns {number[]} Простые множители в неубывающем порядке.
 */
function factorize(number) {
  const factors = [];
  let rest = number;

  // Двойки выносятся отдельно, чтобы дальше перебирать только нечетные делители
  while (rest % 2 === 0) {
    factors.push(2);
    rest = rest / 2;
  }

  // Условие i * i <= rest эквивалентно i <= √rest, но не требует вычисления
  // корня на каждой итерации. Граница сужается по мере деления rest
  for (let i = 3; i * i <= rest; i += 2) {
    while (rest % i === 0) {
      factors.push(i);
      rest = rest / i;
    }
  }

  // Остаток, превышающий единицу, - это простой делитель, больший √number
  if (rest > 1) {
    factors.push(rest);
  }

  return factors;
}

function solve() {
  const number = readInt();
  const factorization = factorize(number);
  process.stdout.write(`${factorization.join(' ')}`);
}

run(solve);
