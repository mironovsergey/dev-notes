/**
 * C. Странное сравнение
 *
 * https://contest.yandex.ru/contest/23991/problems/C/
 *
 * Жители Алгосского архипелага придумали новый способ сравнения строк. Две
 * строки считаются равными, если символы одной из них можно заменить на символы
 * другой так, что первая строка станет точной копией второй строки. При этом
 * необходимо соблюдение двух условий:
 *
 * 1. Порядок вхождения символов должен быть сохранен.
 * 2. Одинаковым символам первой строки должны соответствовать одинаковые
 *    символы второй строки. Разным символам - разные.
 *
 * Например, если строка s = «abacaba», то ей будет равна строка t = «xhxixhx»,
 * так как все вхождения «a» заменены на «x», «b» - на «h», а «c» - на «i».
 * Если же первая строка s=«abc», а вторая t=«aaa», то строки уже не будут
 * равны, так как разные буквы первой строки соответствуют одинаковым буквам
 * второй.
 *
 * Формат ввода
 * В первой строке записана строка s, во второй - строка t. Длины обеих строк
 * не превосходят 10^6. Обе строки содержат хотя бы по одному символу и состоят
 * только из маленьких латинских букв.
 *
 * Строки могут быть разной длины.
 *
 * Формат вывода
 * Выведите «YES», если строки равны (согласно вышеописанным правилам), и «NO»
 * в ином случае.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const s = readLine();
  const t = readLine();

  process.stdout.write(`${compareStrings(s, t) ? 'YES' : 'NO'}`);
}

/**
 * Проверяет, совпадают ли строки с точностью до переименования символов.
 *
 * Соответствие должно быть взаимно однозначным, поэтому проверяются обе
 * стороны: разные символы s не могут переходить в один символ t, и наоборот.
 * Одного отображения недостаточно - при s = «ab», t = «aa» оно непротиворечиво,
 * но букве «a» второй строки отвечают сразу две буквы первой.
 *
 * Оба соответствия строятся за один проход: как только для очередной пары
 * найдено расхождение с уже записанным, ответ отрицательный.
 *
 * Время: O(n). Память: O(размера алфавита).
 *
 * @param {string} s Первая строка.
 * @param {string} t Вторая строка.
 * @returns {boolean} true, если строки равны с точностью до переименования.
 */
function compareStrings(s, t) {
  if (s.length !== t.length) {
    return false;
  }

  const forward = new Map();
  const backward = new Map();

  for (let i = 0; i < s.length; i++) {
    const from = s[i];
    const to = t[i];

    const mappedTo = forward.get(from);
    const mappedFrom = backward.get(to);

    if (mappedTo === undefined && mappedFrom === undefined) {
      forward.set(from, to);
      backward.set(to, from);
      continue;
    }

    if (mappedTo !== to || mappedFrom !== from) {
      return false;
    }
  }

  return true;
}

run(solve);
