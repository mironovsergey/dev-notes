/**
 * B. Соревнование
 *
 * https://contest.yandex.ru/contest/23991/problems/B/
 *
 * Жители Алгосов любят устраивать турниры по спортивному программированию. Все
 * участники разбиваются на пары и соревнуются друг с другом. А потом два самых
 * сильных программиста встречаются в финальной схватке, которая состоит
 * из нескольких раундов. Если в очередном раунде выигрывает первый участник,
 * в таблицу с результатами записывается 0, если второй, то 1. Ничьей в раунде
 * быть не может.
 *
 * Нужно определить наибольший по длине непрерывный отрезок раундов,
 * по результатам которого суммарно получается ничья. Например, если дана
 * последовательность 0 0 1 0 1 1 1 0 0 0, то раунды с 2-го по 9-й (нумерация
 * начинается с единицы) дают ничью.
 *
 * Формат ввода
 * В первой строке задается n (0 ≤ n ≤ 10^5) - количество раундов. Во второй
 * строке через пробел записано n чисел - результаты раундов. Каждое число равно
 * либо 0, либо 1.
 *
 * Формат вывода
 * Выведите длину найденного отрезка.
 */

const { run, readInt, readArray } = require('../../lib/io');

function solve() {
  readInt(); // количество раундов, длина следующей строки
  const results = readArray();

  process.stdout.write(`${getMaxSegmentSize(results)}`);
}

/**
 * Возвращает длину наибольшего отрезка, на котором победы игроков поровну.
 *
 * Победа первого игрока считается за -1, второго за +1, и поддерживается
 * префиксная сумма. Отрезок (i, j] дает ничью тогда и только тогда, когда
 * префиксные суммы в точках i и j равны. Значит, для каждого значения суммы
 * достаточно запомнить самое раннее место, где оно встретилось: любое более
 * позднее совпадение дает отрезок не длиннее.
 *
 * Значение 0 записывается с индексом -1, чтобы учесть отрезки, начинающиеся
 * с первого раунда.
 *
 * Время: O(n) в среднем. Память: O(n).
 *
 * @param {number[]} results Результаты раундов: 0 - победа первого, 1 - второго.
 * @returns {number} Длина наибольшего ничейного отрезка.
 */
function getMaxSegmentSize(results) {
  const sumMap = new Map();
  let maxSegmentSize = 0;
  let currentSum = 0;

  // Изначально у нас 0 раундов до текущего момента
  sumMap.set(0, -1);

  for (let i = 0; i < results.length; i++) {
    // Если выиграл первый -1, если второй +1
    currentSum += results[i] === 0 ? -1 : 1;

    if (sumMap.has(currentSum)) {
      maxSegmentSize = Math.max(maxSegmentSize, i - sumMap.get(currentSum));
    } else {
      sumMap.set(currentSum, i);
    }
  }

  return maxSegmentSize;
}

run(solve);
