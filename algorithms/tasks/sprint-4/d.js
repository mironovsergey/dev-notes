/**
 * D. Полиномиальный хеш
 *
 * https://contest.yandex.ru/contest/23991/problems/D/
 *
 * Алле очень понравился алгоритм вычисления полиномиального хеша. Помогите ей
 * написать функцию, вычисляющую хеш строки s. В данной задаче необходимо
 * использовать в качестве значений отдельных символов их коды в таблице ASCII.
 *
 * Формат ввода
 * В первой строке дано число a (1 ≤ a ≤ 1000) - основание, по которому считается хеш.
 *
 * Во второй строке дано число m (1 ≤ m ≤ 10^9) - модуль.
 *
 * В третьей строке дана строка s (0 ≤ |s| ≤ 10^6), состоящая из больших
 * и маленьких латинских букв.
 *
 * Формат вывода
 * Выведите целое неотрицательное число - хеш заданной строки.
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const a = readInt(); // основание, по которому считается хеш
  const m = readInt(); // модуль
  const s = readLine(); // строка

  process.stdout.write(`${polynomialHash(s, a, m)}`);
}

/**
 * Возвращает полиномиальный хеш строки, вычисленный методом Горнера.
 *
 * Взятие остатка на каждом шаге удерживает hash в пределах [0, m), поэтому
 * произведение hash * a не превосходит m * a. При ограничениях задачи
 * (m <= 10^9, a <= 1000) это до 10^12 - заметно меньше 2^53, границы точного
 * представления целых чисел, так что потери разрядов не происходит.
 *
 * Время: O(n). Память: O(1).
 *
 * @param {string} s Хешируемая строка.
 * @param {number} a Основание, по которому считается хеш.
 * @param {number} m Модуль.
 * @returns {number} Хеш строки в диапазоне [0, m).
 */
function polynomialHash(s, a, m) {
  let hash = 0;

  for (let i = 0; i < s.length; i++) {
    hash = (hash * a + s.charCodeAt(i)) % m;
  }

  return hash;
}

run(solve);
