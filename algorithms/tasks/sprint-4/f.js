/**
 * F. Префиксные хеши
 *
 * https://contest.yandex.ru/contest/23991/problems/F/
 *
 * Алла не остановилась на достигнутом - теперь она хочет научиться быстро
 * вычислять хеши произвольных подстрок данной строки. Помогите ей!
 *
 * На вход поступают запросы на подсчет хешей разных подстрок. Ответ на каждый
 * запрос должен выполняться за O(1). Допустимо в начале работы программы
 * сделать предподсчет для дальнейшей работы со строкой.
 *
 * В данной задаче необходимо использовать в качестве значений отдельных
 * символов их коды в таблице ASCII.
 *
 * Формат ввода
 * В первой строке дано число a (1 ≤ a ≤ 1000) - основание, по которому
 * считается хеш. Во второй строке дано число m (1 ≤ m ≤ 10^7) - модуль.
 * В третьей строке дана строка s (0 ≤ |s| ≤ 10^6), состоящая из больших
 * и маленьких латинских букв.
 *
 * В четвертой строке дано число запросов t - натуральное число от 1 до 10^5.
 * В каждой из следующих t строк записаны через пробел два числа l и r - индексы
 * начала и конца очередной подстроки. (1 ≤ l ≤ r ≤ |s|).
 *
 * Формат вывода
 * Для каждого запроса выведите на отдельной строке хеш заданной в запросе
 * подстроки.
 */

const { run, readInt, readLine, readArray } = require('../../lib/io');

function solve() {
  const a = readInt(); // основание, по которому считается хеш
  const m = readInt(); // модуль
  const s = readLine(); // строка
  const t = readInt(); // число запросов

  const { hashes, powers } = calculatePrefixHashes(s, a, m);

  const output = new Array(t);

  for (let i = 0; i < t; i++) {
    const [l, r] = readArray();

    output[i] = calculateSubstringHash(hashes, powers, l, r, m);
  }

  // Накопление в массив вместо t вызовов write: при t до 10^5
  // это заметно дешевле по системным вызовам
  process.stdout.write(t === 0 ? '' : `${output.join('\n')}\n`);
}

/**
 * Вычисляет хеши всех префиксов строки и степени основания.
 *
 * Время: O(n). Память: O(n).
 *
 * @param {string} s Входная строка.
 * @param {number} a Основание, по которому считается хеш.
 * @param {number} m Модуль.
 * @returns {{hashes: number[], powers: number[]}} Массивы длины n + 1:
 *   hashes[i] - хеш префикса длины i, powers[i] - a^i по модулю m.
 */
function calculatePrefixHashes(s, a, m) {
  const n = s.length;
  const hashes = new Array(n + 1).fill(0);
  const powers = new Array(n + 1).fill(1);

  for (let i = 1; i <= n; i++) {
    powers[i] = (powers[i - 1] * a) % m;
  }

  for (let i = 1; i <= n; i++) {
    hashes[i] = (hashes[i - 1] * a + s.charCodeAt(i - 1)) % m;
  }

  return { hashes, powers };
}

/**
 * Возвращает хеш подстроки по предвычисленным хешам префиксов.
 *
 * Хеш префикса длины r содержит вклад префикса длины l - 1, сдвинутый на
 * r - l + 1 позиций, - его и вычитают.
 *
 * Здесь перемножаются два остатка по модулю m, поэтому произведение
 * ограничено m². Условие задачи задает m <= 10^7, и m² = 10^14 остается ниже
 * 2^53 - границы точного представления целых чисел. При большем модуле
 * результат молча терял бы младшие разряды.
 *
 * Время: O(1). Память: O(1).
 *
 * @param {number[]} hashes Хеши префиксов.
 * @param {number[]} powers Степени основания.
 * @param {number} l Индекс начала подстроки, нумерация с единицы.
 * @param {number} r Индекс конца подстроки включительно, нумерация с единицы.
 * @param {number} m Модуль.
 * @returns {number} Хеш подстроки в диапазоне [0, m).
 */
function calculateSubstringHash(hashes, powers, l, r, m) {
  const difference = (hashes[r] - hashes[l - 1] * powers[r - l + 1]) % m;

  // Разность может быть отрицательной: остаток в JavaScript
  // берет знак делимого
  return (difference + m) % m;
}

run(solve);
