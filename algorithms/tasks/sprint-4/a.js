/**
 * A. Кружки
 *
 * https://contest.yandex.ru/contest/23991/problems/A/
 *
 * В компании, где работает Тимофей, заботятся о досуге сотрудников и устраивают
 * различные кружки по интересам. Когда кто-то записывается на занятие, в лог
 * вносится название кружка.
 *
 * По записям в логе составьте список всех кружков, в которые ходит хотя бы один
 * человек.
 *
 * Формат ввода
 * В первой строке дается натуральное число n, не превосходящее
 * 10 000 - количество записей в логе.
 *
 * В следующих n строках - названия кружков.
 *
 * Формат вывода
 * Выведите уникальные названия кружков по одному на строке, в порядке появления
 * во входных данных.
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const n = readInt(); // количество записей в логе
  const log = [];

  for (let i = 1; i <= n; i++) {
    log.push(readLine());
  }

  const uniqueLog = uniqueValues(log);

  for (let i = 0; i < uniqueLog.length; i++) {
    process.stdout.write(`${uniqueLog[i]}\n`);
  }
}

/**
 * Убирает дубликаты, сохраняя порядок первого появления.
 *
 * Set в JavaScript сохраняет порядок вставки, поэтому дополнительная
 * стабилизация не требуется.
 *
 * Время: O(n) в среднем. Память: O(n).
 *
 * @param {string[]} values Исходные значения.
 * @returns {string[]} Уникальные значения в порядке первого появления.
 */
function uniqueValues(values) {
  return [...new Set(values)];
}

run(solve);
