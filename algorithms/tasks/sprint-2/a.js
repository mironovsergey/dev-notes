/**
 * A. Мониторинг
 *
 * https://contest.yandex.ru/contest/22779/problems/A/
 *
 * Алла получила задание, связанное с мониторингом работы различных серверов.
 * Требуется понять, сколько времени обрабатываются определенные запросы на
 * конкретных серверах. Эту информацию нужно хранить в матрице, где номер
 * столбца соответствуют идентификатору запроса, а номер строки - идентификатору
 * сервера. Алла перепутала строки и столбцы местами. С каждым бывает. Помогите
 * ей исправить баг.
 *
 * Есть матрица размера m × n. Нужно написать функцию, которая ее транспонирует.
 *
 * Транспонированная матрица получается из исходной заменой строк на столбцы.
 *
 * Формат ввода
 * В первой строке задано число n - количество строк матрицы.
 * Во второй строке задано m - число столбцов, m и n не превосходят 1000.
 * В следующих n строках задана матрица. Числа в ней не превосходят по модулю
 * 1000.
 *
 * Формат вывода
 * Напечатайте транспонированную матрицу в том же формате, который задан во
 * входных данных. Каждая строка матрицы выводится на отдельной строке, элементы
 * разделяются пробелами.
 */

const { run, readInt, readMatrix } = require('../../lib/io');

/**
 * Транспонирует матрицу: строки исходной матрицы становятся столбцами.
 *
 * Размеры передаются явно, потому что строка исходной матрицы может оказаться
 * короче объявленного числа столбцов, если во входных данных есть пропуски.
 *
 * Время: O(rows * cols). Память: O(rows * cols) на результат.
 *
 * @param {number[][]} matrix Исходная матрица размера rows x cols.
 * @param {number} rows Количество строк исходной матрицы.
 * @param {number} cols Количество столбцов исходной матрицы.
 * @returns {number[][]} Транспонированная матрица размера cols x rows.
 */
function transposeMatrix(matrix, rows, cols) {
  const result = [];

  for (let j = 0; j < cols; j++) {
    result[j] = [];
    for (let i = 0; i < rows; i++) {
      result[j][i] = matrix[i][j];
    }
  }

  return result;
}

function solve() {
  const rows = readInt();
  const cols = readInt();
  const matrix = readMatrix(rows);

  process.stdout.write(
    `${transposeMatrix(matrix, rows, cols)
      .map((row) => row.join(' '))
      .join('\n')}`,
  );
}

run(solve);
