/**
 * A. Генератор скобок
 *
 * https://contest.yandex.ru/contest/23638/problems/A/
 *
 * Рита по поручению Тимофея наводит порядок в правильных скобочных
 * последовательностях (ПСП), состоящих только из круглых скобок (). Для этого
 * ей надо сгенерировать все ПСП длины 2n в алфавитном порядке - алфавит состоит
 * из ( и ) и открывающая скобка идет раньше закрывающей.
 *
 * Помогите Рите - напишите программу, которая по заданному n выведет все ПСП
 * в нужном порядке.
 *
 * Рассмотрим второй пример. Надо вывести ПСП из четырех символов.
 * Таких всего две:
 * 1. (())
 * 2. ()()
 * (()) идет раньше ()(), так как первый символ у них одинаковый, а на второй
 * позиции у первой ПСП стоит (, который идет раньше ).
 *
 * Формат ввода
 * На вход функция принимает n - целое число от 0 до 10.
 *
 * Формат вывода
 * Функция должна напечатать все возможные скобочные последовательности заданной
 * длины в алфавитном (лексикографическом) порядке.
 */

const { run, readInt } = require('../../lib/io');

function solve() {
  const n = readInt(); // длина правильной скобочной последовательности
  const brackets = generateBrackets(n);

  for (let i = 0; i < brackets.length; i++) {
    process.stdout.write(`${brackets[i]}\n`);
  }
}

/**
 * Возвращает все правильные скобочные последовательности из n пар скобок
 * в лексикографическом порядке.
 *
 * Ветви, из которых правильную последовательность получить уже нельзя, не
 * строятся: открывающих скобок не может быть больше n, а закрывающих - больше,
 * чем уже открытых. Благодаря отсечению число листьев дерева перебора равно
 * числу Каталана Cn, а не 2^(2n).
 *
 * Скобка «(» перебирается раньше «)», поэтому результат сразу получается
 * лексикографически упорядоченным и дополнительной сортировки не требует.
 *
 * Время: O(n * Cn). Память: O(n) на кадры стека вызовов, не считая результата.
 *
 * @param {number} n Количество пар скобок.
 * @returns {string[]} Все правильные последовательности длины 2n.
 */
function generateBrackets(n) {
  const result = [];

  function backtrack(str, open, close) {
    if (str.length === 2 * n) {
      result.push(str);
      return;
    }

    if (open < n) {
      backtrack(str + '(', open + 1, close);
    }

    if (close < open) {
      backtrack(str + ')', open, close + 1);
    }
  }

  backtrack('', 0, 0);

  return result;
}

run(solve);
