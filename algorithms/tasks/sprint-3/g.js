/**
 * G. Гардероб
 *
 * https://contest.yandex.ru/contest/23638/problems/G/
 *
 * Рита решила оставить у себя одежду только трех цветов: розового, желтого
 * и малинового. После того как вещи других расцветок были убраны, Рита захотела
 * отсортировать свой новый гардероб по цветам. Сначала должны идти вещи
 * розового цвета, потом - желтого, и в конце - малинового. Помогите Рите
 * справиться с этой задачей.
 *
 * Примечание: попробуйте решить задачу за один проход по массиву!
 *
 * Формат ввода
 * В первой строке задано количество предметов в гардеробе: n - оно
 * не превосходит 1000000. Во второй строке дается массив, в котором указан цвет
 * для каждого предмета. Розовый цвет обозначен 0, желтый - 1, малиновый - 2.
 *
 * Формат вывода
 * Нужно вывести в строку через пробел цвета предметов в правильном порядке.
 */

const { run, readInt, readArray } = require('../../lib/io');

const PINK = 0;
const YELLOW = 1;

function solve() {
  readInt(); // количество предметов, длина следующей строки
  const colors = readArray();

  process.stdout.write(`${sortClothes(colors).join(' ')}`);
}

/**
 * Сортирует предметы по трем цветам за один проход по массиву.
 *
 * Разбиение голландского флага: три указателя делят массив на четыре зоны.
 * Инвариант - левее low все элементы розовые, на отрезке [low, mid) желтые,
 * правее high малиновые, а отрезок [mid, high] еще не просмотрен.
 *
 * Сортировка подсчетом решает ту же задачу за O(n), но требует двух проходов:
 * сначала подсчет, затем перезапись. Здесь проход один, как и предлагает
 * условие, и дополнительной памяти не требуется вовсе.
 *
 * Время: O(n). Память: O(1).
 *
 * @param {number[]} colors Цвета предметов: 0 розовый, 1 желтый, 2 малиновый.
 *   Массив изменяется на месте.
 * @returns {number[]} Тот же массив, упорядоченный по цветам.
 */
function sortClothes(colors) {
  let low = 0;
  let mid = 0;
  let high = colors.length - 1;

  while (mid <= high) {
    if (colors[mid] === PINK) {
      [colors[low], colors[mid]] = [colors[mid], colors[low]];
      low++;
      mid++;
    } else if (colors[mid] === YELLOW) {
      mid++;
    } else {
      [colors[mid], colors[high]] = [colors[high], colors[mid]];
      high--;
      // mid намеренно не сдвигается: пришедший справа элемент еще не просмотрен
    }
  }

  return colors;
}

run(solve);
