/**
 * H. Большое число
 *
 * https://contest.yandex.ru/contest/23638/problems/H/
 *
 * Вечером ребята решили поиграть в игру «Большое число».
 * Даны числа. Нужно определить, какое самое большое число можно из них
 * составить.
 *
 * Формат ввода
 * В первой строке записано n - количество чисел. Оно не превосходит 100.
 * Во второй строке через пробел записаны n неотрицательных чисел, каждое
 * из которых не превосходит 1000.
 *
 * Формат вывода
 * Нужно вывести самое большое число, которое можно составить из данных чисел.
 */

const { run, readInt, readArray } = require('../../lib/io');

function solve() {
  readInt(); // количество чисел, длина следующей строки
  const numbers = readArray();

  process.stdout.write(bigNumber(numbers));
}

/**
 * Возвращает наибольшее число, которое можно составить приписыванием
 * данных чисел друг к другу.
 *
 * Числа сортируются компаратором «пара ab больше пары ba»: из двух соседей
 * первым должен идти тот, который дает большую конкатенацию. Сравнение по
 * убыванию самого числа неверно - например, 9 и 91 дают 991, а не 919.
 *
 * Сравнивать длины не нужно: обе конкатенации ab и ba имеют одинаковую длину,
 * поэтому лексикографическое сравнение строк совпадает с числовым.
 *
 * Время: O(n log n) сравнений, каждое стоит O(d), где d - длина записи числа.
 * Память: O(n) на результат.
 *
 * @param {number[]} numbers Неотрицательные числа; массив сортируется.
 * @returns {string} Наибольшее составленное число.
 */
function bigNumber(numbers) {
  const digits = numbers.map((number) => `${number}`);

  digits.sort((a, b) => {
    const ab = a + b;
    const ba = b + a;

    if (ab === ba) {
      return 0;
    }

    return ab > ba ? -1 : 1;
  });

  const result = digits.join('');

  // Если наибольшим оказался ноль, значит, все числа нулевые: «000» - не число,
  // наибольшее составленное число равно нулю
  return result[0] === '0' ? '0' : result;
}

run(solve);
