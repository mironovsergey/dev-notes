/**
 * D. Печеньки
 *
 * https://contest.yandex.ru/contest/23638/problems/D/
 *
 * К Васе в гости пришли одноклассники. Его мама решила угостить ребят печеньем.
 *
 * Но не все так просто. Печенья могут быть разного размера. А у каждого ребенка
 * есть фактор жадности - минимальный размер печенья, которое он возьмет. Нужно
 * выяснить, сколько ребят останутся довольными в лучшем случае, когда они
 * действуют оптимально.
 *
 * Каждый ребенок может взять не больше одного печенья.
 *
 * Формат ввода
 * В первой строке записано n - количество детей.
 *
 * Во второй - n чисел, разделенных пробелом, каждое из которых - фактор
 * жадности ребенка. Это натуральные числа, не превосходящие 1000.
 *
 * В следующей строке записано число m - количество печенек.
 *
 * Далее - m натуральных чисел, разделенных пробелом - размеры печенек.
 * Размеры печенек не превосходят 1000.
 *
 * Оба числа n и m не превосходят 10000.
 *
 * Формат вывода
 * Нужно вывести одно число - количество детей, которые останутся довольными.
 */

const { run, readInt, readArray } = require('../../lib/io');

function solve() {
  readInt(); // количество детей, длина следующей строки
  const greedFactors = readArray();

  readInt(); // количество печенек, длина следующей строки
  const cookies = readArray();

  process.stdout.write(`${countSatisfiedChildren(greedFactors, cookies)}`);
}

/**
 * Возвращает количество детей, которым досталась подходящая печенька.
 *
 * Жадная стратегия: оба массива сортируются, после чего каждому ребенку по
 * возрастанию жадности выдается наименьшая из еще не розданных подходящих
 * печенек. Выбор корректен, потому что отдать более крупную печенье ребенку,
 * которому хватило бы меньшей, никогда не выгодно: крупная может понадобиться
 * более жадному ребенку, а меньшая ему уже не подойдет.
 *
 * Время: O(n log n + m log m) на сортировки. Память: O(1) сверх сортировок.
 *
 * @param {number[]} greedFactors Факторы жадности детей; массив сортируется.
 * @param {number[]} cookies Размеры печенек; массив сортируется.
 * @returns {number} Количество довольных детей.
 */
function countSatisfiedChildren(greedFactors, cookies) {
  greedFactors.sort((a, b) => a - b);
  cookies.sort((a, b) => a - b);

  let cookieIndex = 0;
  let counter = 0;

  for (let factor of greedFactors) {
    while (cookieIndex < cookies.length && cookies[cookieIndex] < factor) {
      cookieIndex++;
    }
    if (cookieIndex < cookies.length) {
      cookieIndex++;
      counter++;
    } else {
      break;
    }
  }

  return counter;
}

run(solve);
