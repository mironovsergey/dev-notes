/**
 * C. Подпоследовательность
 *
 * https://contest.yandex.ru/contest/23638/problems/C/
 *
 * Гоша любит играть в игру «Подпоследовательность»: даны 2 строки, и нужно
 * понять, является ли первая из них подпоследовательностью второй. Когда строки
 * достаточно длинные, очень трудно получить ответ на этот вопрос, просто
 * посмотрев на них. Помогите Гоше написать функцию, которая решает эту задачу.
 *
 * Формат ввода
 * В первой строке записана строка s.
 * Во второй - строка t.
 * Обе строки состоят из маленьких латинских букв, длины строк не превосходят
 * 150000. Строки не могут быть пустыми.
 *
 * Формат вывода
 * Выведите True, если s является подпоследовательностью t, иначе - False.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const s = readLine();
  const t = readLine();

  process.stdout.write(`${isSubsequence(s, t) ? 'True' : 'False'}`);
}

/**
 * Проверяет, является ли строка s подпоследовательностью строки t.
 *
 * Метод двух указателей: указатель по t движется всегда, указатель по s - только
 * при совпадении символов. Жадный выбор корректен, потому что брать самое раннее
 * возможное вхождение очередного символа никогда не хуже: оно оставляет для
 * остатка s наибольший возможный суффикс t.
 *
 * Время: O(|t|). Память: O(1).
 *
 * @param {string} s Проверяемая подпоследовательность.
 * @param {string} t Строка, в которой выполняется поиск.
 * @returns {boolean} true, если s является подпоследовательностью t.
 */
function isSubsequence(s, t) {
  let sIndex = 0;
  let tIndex = 0;

  while (sIndex < s.length && tIndex < t.length) {
    if (s[sIndex] === t[tIndex]) {
      sIndex++;
    }

    tIndex++;
  }

  return sIndex === s.length;
}

/**
 * Рекурсивный вариант той же проверки - приведен для сравнения.
 *
 * По условию длина строк доходит до 150000, а глубина рекурсии здесь равна |t|,
 * поэтому на предельных данных вызов завершается ошибкой
 * RangeError: Maximum call stack size exceeded. Рекурсия хвостовая, и движки
 * JavaScript ее не оптимизируют, так что итеративная версия выше - не просто
 * стилистическое предпочтение, а единственный работающий вариант.
 *
 * Время: O(|t|). Память: O(|t|) на кадры стека вызовов.
 *
 * @param {string} s Проверяемая подпоследовательность.
 * @param {string} t Строка, в которой выполняется поиск.
 * @param {number} sLength Количество еще не сопоставленных символов s.
 * @param {number} tLength Количество еще не просмотренных символов t.
 * @returns {boolean} true, если s является подпоследовательностью t.
 */
function isSubsequenceRecursive(s, t, sLength = s.length, tLength = t.length) {
  if (sLength === 0) {
    return true;
  }

  if (tLength === 0) {
    return false;
  }

  if (s[sLength - 1] === t[tLength - 1]) {
    return isSubsequenceRecursive(s, t, sLength - 1, tLength - 1);
  }

  return isSubsequenceRecursive(s, t, sLength, tLength - 1);
}

run(solve);
