/**
 * B. Комбинации
 *
 * https://contest.yandex.ru/contest/23638/problems/B/
 *
 * На клавиатуре старых мобильных телефонов каждой цифре соответствовало
 * несколько букв. Примерно так:
 *
 * 2:'abc',
 * 3:'def',
 * 4:'ghi',
 * 5:'jkl',
 * 6:'mno',
 * 7:'pqrs',
 * 8:'tuv',
 * 9:'wxyz'
 *
 * Вам известно в каком порядке были нажаты кнопки телефона, без учета повторов.
 * Напечатайте все комбинации букв, которые можно набрать такой
 * последовательностью нажатий.
 *
 * Формат ввода
 * На вход подается строка, состоящая из цифр 2-9 включительно. Длина строки
 * не превосходит 10 символов.
 *
 * Формат вывода
 * Выведите все возможные комбинации букв через пробел в лексикографическом
 * (алфавитном) порядке по возрастанию.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const digits = readLine(); // цифры клавиатуры телефона
  const combinations = generateCombinations(digits);

  process.stdout.write(`${combinations.join(' ')}`);
}

const PHONE_LETTERS = new Map([
  ['2', 'abc'],
  ['3', 'def'],
  ['4', 'ghi'],
  ['5', 'jkl'],
  ['6', 'mno'],
  ['7', 'pqrs'],
  ['8', 'tuv'],
  ['9', 'wxyz'],
]);

/**
 * Возвращает все комбинации букв, соответствующие последовательности цифр,
 * в лексикографическом порядке.
 *
 * Буквы каждой цифры перебираются по возрастанию, а обход дерева вариантов
 * идет в глубину слева направо, поэтому комбинации порождаются сразу в нужном
 * порядке - сортировать результат не нужно.
 *
 * Время: O(L * 4^L), где L - количество цифр: столько всего комбинаций, и
 * каждая имеет длину L. Память: O(L) на кадры стека вызовов.
 *
 * @param {string} digits Строка из цифр 2-9.
 * @returns {string[]} Все комбинации букв в лексикографическом порядке.
 */
function generateCombinations(digits) {
  const result = [];

  const backtrack = (index, prefix) => {
    if (index === digits.length) {
      result.push(prefix);
      return;
    }

    for (const letter of PHONE_LETTERS.get(digits[index])) {
      backtrack(index + 1, prefix + letter);
    }
  };

  backtrack(0, '');

  return result;
}

run(solve);
