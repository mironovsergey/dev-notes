/**
 * E. Покупка домов
 *
 * https://contest.yandex.ru/contest/23638/problems/E/
 *
 * Тимофей решил купить несколько домов на знаменитом среди разработчиков
 * Алгосском архипелаге. Он нашел n объявлений о продаже, где указана стоимость
 * каждого дома в алгосских франках. А у Тимофея есть k франков. Помогите ему
 * определить, какое наибольшее количество домов на Алгосах он сможет приобрести
 * за эти деньги.
 *
 * Формат ввода
 * В первой строке через пробел записаны натуральные числа n и k.
 *
 * n - количество домов, которые рассматривает Тимофей, не превосходит 100000;
 *
 * k - общий бюджет, не превосходит 100000;
 *
 * В следующей строке через пробел записано n стоимостей домов. Каждое из чисел
 * не превосходит 100000. Все стоимости - натуральные числа.
 *
 * Формат вывода
 * Выведите одно число - наибольшее количество домов, которое может купить
 * Тимофей.
 */

const { run, readArray } = require('../../lib/io');

function solve() {
  // Количество домов и общий бюджет
  const [, budget] = readArray();
  const prices = readArray();

  process.stdout.write(`${countHouses(budget, prices)}`);
}

/**
 * Возвращает наибольшее количество домов, которые можно купить в пределах
 * бюджета.
 *
 * Жадная стратегия: дома покупаются в порядке возрастания цены. Выбор
 * корректен, потому что для любого набора из k домов набор из k самых дешевых
 * стоит не больше, - значит, если купить k домов вообще возможно, то возможно
 * и купить k самых дешевых.
 *
 * Время: O(n log n) на сортировку. Память: O(1) сверх сортировки.
 *
 * @param {number} budget Общий бюджет.
 * @param {number[]} prices Стоимости домов; массив сортируется.
 * @returns {number} Наибольшее количество домов, укладывающееся в бюджет.
 */
function countHouses(budget, prices) {
  prices.sort((a, b) => a - b);

  let totalCost = 0;
  let counter = 0;

  for (let i = 0; i < prices.length; i++) {
    // Как только очередной дом не помещается в остаток бюджета, не поместится
    // и любой следующий: цены отсортированы по возрастанию
    if (totalCost + prices[i] <= budget) {
      totalCost += prices[i];
      counter++;
    } else {
      break;
    }
  }

  return counter;
}

run(solve);
