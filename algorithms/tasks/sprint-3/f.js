/**
 * F. Периметр треугольника
 *
 * https://contest.yandex.ru/contest/23638/problems/F/
 *
 * Перед сном Рита решила поиграть в игру на телефоне. Дан массив целых чисел,
 * в котором каждый элемент обозначает длину стороны треугольника. Нужно
 * определить максимально возможный периметр треугольника, составленного
 * из сторон с длинами из заданного массива. Помогите Рите скорее закончить игру
 * и пойти спать.
 *
 * Напомним, что из трех отрезков с длинами a ≤ b ≤ c можно составить
 * треугольник, если выполнено неравенство треугольника: c < a + b
 *
 * Разберем пример:
 * даны длины сторон 6, 3, 3, 2. Попробуем в качестве наибольшей стороны
 * выбрать 6. Неравенство треугольника не может выполниться, так как остались
 * 3, 3, 2 - максимальная сумма из них равна 6.
 *
 * Без шестерки оставшиеся три отрезка уже образуют треугольник со сторонами
 * 3, 3, 2. Неравенство выполняется: 3 < 3 + 2. Периметр равен 3 + 3 + 2 = 8.
 *
 * Формат ввода
 * В первой строке записано количество отрезков n, 3 ≤ n ≤ 10000.
 *
 * Во второй строке записано n неотрицательных чисел, не превосходящих
 * 10 000, - длины отрезков.
 *
 * Формат вывода
 * Нужно вывести одно число - наибольший периметр треугольника.
 *
 * Гарантируется, что тройка чисел, которая может образовать треугольник,
 * всегда есть.
 */

const { run, readInt, readArray } = require('../../lib/io');

function solve() {
  readInt(); // количество отрезков, длина следующей строки
  const lengths = readArray();

  process.stdout.write(`${maxPerimeter(lengths)}`);
}

/**
 * Возвращает наибольший периметр треугольника, составленного из трех отрезков.
 *
 * После сортировки достаточно проверять только тройки соседних элементов,
 * двигаясь от наибольшего. Для фиксированной наибольшей стороны lengths[i]
 * сумма двух других максимальна именно у соседей lengths[i-1] и lengths[i-2],
 * поэтому если неравенство треугольника не выполнено для них, оно не выполнено
 * ни для какой другой пары с этой наибольшей стороной. Первая же подходящая
 * тройка дает максимальный периметр, так как рассматривается в порядке
 * убывания сторон.
 *
 * Время: O(n log n) на сортировку. Память: O(1) сверх сортировки.
 *
 * @param {number[]} lengths Длины отрезков; массив сортируется.
 * @returns {number} Наибольший периметр либо 0, если треугольник не составить.
 */
function maxPerimeter(lengths) {
  lengths.sort((a, b) => a - b);

  let perimeter = 0;

  for (let i = lengths.length - 1; i >= 2; i--) {
    // Проверяем условие треугольника: сумма двух меньших сторон
    // должна быть больше самой большой стороны
    if (lengths[i - 2] + lengths[i - 1] > lengths[i]) {
      // Если условие выполняется, значит,
      // нашли тройку сторон для треугольника
      // Обновляем максимально найденный периметр
      perimeter = lengths[i] + lengths[i - 1] + lengths[i - 2];
      // Как только нашли первый подходящий треугольник, выходим из цикла
      break;
    }
  }

  return perimeter;
}

run(solve);
