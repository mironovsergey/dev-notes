/**
 * F. Максимальная глубина
 *
 * https://contest.yandex.ru/contest/24809/problems/F/
 *
 * Алла хочет побывать на разных островах архипелага Алгосы. Она составила
 * карту. Карта представлена в виде дерева: корень обозначает центр архипелага,
 * узлы - другие острова. А листья - это дальние острова, на которые Алла хочет
 * попасть.
 *
 * Помогите Алле определить максимальное число островов, через которые ей нужно
 * пройти для совершения одной поездки от стартового острова до места
 * назначения, включая начальный и конечный пункты.
 *
 * Формат ввода
 * На вход подается корень дерева.
 *
 * Формат вывода
 * Функция должна вернуть число, равное максимальному числу островов в пути
 * (включая начальный и конечный пункты).
 */

/**
 * Возвращает высоту дерева в вершинах.
 *
 * Время: O(n). Память: O(h) на кадры стека вызовов.
 *
 * @param {CNode|null} root Корень дерева.
 * @returns {number} Высота: 0 для пустого дерева, 1 для одиночной вершины.
 */
function solution(root) {
  // Если узел пустой (null), то возвращаем глубину 0
  if (root === null) {
    return 0;
  }

  // Рекурсивно вычисляем глубину для левого и правого поддеревьев
  let leftDepth = solution(root.left);
  let rightDepth = solution(root.right);

  // Возвращаем максимальную глубину из глубины левого и правого поддеревьев,
  // увеличенную на 1 для учета текущего узла
  return Math.max(leftDepth, rightDepth) + 1;
}

// Локальная проверка. Проверяющая система объявляет класс CNode самостоятельно,
// поэтому и объявление, и тесты выполняются только при локальном запуске.
// Объявление внутри блока видно лишь внутри него - это ровно то, что нужно.
if (process.env.REMOTE_JUDGE !== 'true') {
  const assert = require('assert');

  class CNode {
    constructor(value, left = null, right = null) {
      this.value = value;
      this.left = left;
      this.right = right;
    }
  }

  assert.strictEqual(
    solution(new CNode(5, new CNode(3, new CNode(1), new CNode(4)), new CNode(8))),
    3,
  );
  assert.strictEqual(solution(null), 0);
  assert.strictEqual(solution(new CNode(1)), 1);
  assert.strictEqual(solution(new CNode(1, new CNode(2, new CNode(3)))), 3);

  console.log('f.js: OK');
}
