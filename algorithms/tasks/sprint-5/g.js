/**
 * G. Максимальный путь в дереве
 *
 * https://contest.yandex.ru/contest/24809/problems/G/
 *
 * Тимофей устраивает соревнования по спортивному ориентированию в своем офисе.
 * Схема офиса представлена в виде дерева. Посещая каждый пункт, можно
 * зарабатывать или терять очки. Если в узле записано положительное число, это
 * значение добавляется к текущему количеству очков участника. Если
 * отрицательное - очки вычитаются. Если 0 - их количество не меняется.
 *
 * Нужно определить, какое максимальное число очков можно заработать, пройдя по
 * пути из какого-то пункта A в какой-то (возможно, тот же) пункт B.
 *
 * Путь не обязательно должен проходить через корень или содержать лист. Путь
 * должен содержать по крайней мере один узел.
 *
 * Требования к решению: передаваемое в качестве аргумента дерево нельзя менять.
 * Не храните вспомогательную информацию в вершинах.
 *
 * Формат ввода
 * На вход подается корень дерева.
 *
 * Формат вывода
 * Функция должна вернуть число, равное максимальному количеству очков, которое
 * можно заработать, попав из пункта А в пункт В.
 */

/**
 * Возвращает наибольшую сумму значений на пути между двумя вершинами дерева.
 *
 * Путь может подниматься и снова спускаться, поэтому в каждой вершине
 * различаются две величины: сумма пути, который через нее лишь проходит
 * (левая ветвь + вершина + правая ветвь) - она обновляет ответ, и сумма пути,
 * который в ней заканчивается (вершина + лучшая из ветвей) - она возвращается
 * наверх, так как продолжить путь можно только по одной ветви.
 *
 * Отрицательные ветви отбрасываются через Math.max(..., 0): присоединять их
 * невыгодно. Сам ответ при этом инициализируется -Infinity, а не нулем, -
 * путь не может быть пустым, и в дереве из одних отрицательных значений
 * ответом должно быть наибольшее из них.
 *
 * Дерево не изменяется, вспомогательные данные в вершинах не хранятся.
 *
 * Время: O(n). Память: O(h) на кадры стека вызовов.
 *
 * @param {CNode|null} root Корень дерева.
 * @returns {number} Наибольшая сумма значений на пути.
 */
function solution(root) {
  let sum = Number.NEGATIVE_INFINITY;

  // Функция для рекурсивного поиска максимальной суммы на пути,
  // начинающемся с данного узла
  function maxSum(node) {
    if (node === null) {
      return 0;
    }

    // Рекурсивно находим максимальные суммы для левого
    // и правого поддеревьев
    let left = Math.max(maxSum(node.left), 0);
    let right = Math.max(maxSum(node.right), 0);

    // Обновляем максимальную сумму пути, проходящего через текущий узел
    sum = Math.max(sum, node.value + left + right);

    // Возвращаем максимальное значение пути, начинающегося с текущего узла
    return node.value + Math.max(left, right);
  }

  // Начинаем рекурсивный обход дерева, начиная с корня
  maxSum(root);

  return sum;
}

// Локальная проверка. Проверяющая система объявляет класс CNode самостоятельно,
// поэтому и объявление, и тесты выполняются только при локальном запуске.
// Объявление внутри блока видно лишь внутри него - это ровно то, что нужно.
if (process.env.REMOTE_JUDGE !== 'true') {
  const assert = require('assert');

  class CNode {
    constructor(value, left = null, right = null) {
      this.value = value;
      this.left = left;
      this.right = right;
    }
  }

  assert.strictEqual(
    solution(new CNode(2, new CNode(2), new CNode(-3, new CNode(1), new CNode(5)))),
    6,
  );
  // Все значения отрицательные: путь не может быть пустым
  assert.strictEqual(solution(new CNode(-5)), -5);
  assert.strictEqual(solution(new CNode(-2, new CNode(-1), new CNode(-3))), -1);

  console.log('g.js: OK');
}
