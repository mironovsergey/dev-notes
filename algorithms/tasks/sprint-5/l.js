/**
 * L. Просеивание вниз
 *
 * https://contest.yandex.ru/contest/24809/problems/L/
 *
 * Напишите функцию, совершающую просеивание вниз в куче на максимум.
 * Гарантируется, что порядок элементов в куче может быть нарушен только
 * элементом, от которого запускается просеивание.
 *
 * Функция принимает в качестве аргументов массив, в котором хранятся элементы
 * кучи, и индекс элемента, от которого надо сделать просеивание вниз. Функция
 * должна вернуть индекс, на котором элемент оказался после просеивания. Также
 * необходимо изменить порядок элементов в переданном в функцию массиве.
 *
 * Индексация в массиве, содержащем кучу, начинается с единицы. Таким образом,
 * сыновья вершины на позиции v это 2v и 2v+1. Обратите внимание, что нулевой
 * элемент в передаваемом массиве фиктивный, вершина кучи соответствует 1-му
 * элементу.
 *
 * Формат ввода
 * Элементы кучи - целые числа, лежащие в диапазоне от −10^9 до 10^9. Все
 * элементы кучи уникальны. Передаваемый в функцию индекс лежит в диапазоне
 * от 1 до размера передаваемого массива. В куче содержится от 1 до 10^5
 * элементов.
 */

/**
 * Просеивает элемент вниз в куче на максимум.
 *
 * Обмен выполняется с наибольшим из детей: обмен с меньшим поставил бы его
 * выше собственного брата и нарушил бы свойство кучи заново.
 *
 * Нулевой элемент массива фиктивный, вершина кучи - элемент с индексом 1,
 * поэтому дети вершины v лежат на позициях 2v и 2v + 1.
 *
 * Время: O(log n). Память: O(log n) на кадры стека вызовов.
 *
 * @param {number[]} heap Массив кучи с фиктивным нулевым элементом.
 * @param {number} idx Индекс просеиваемого элемента.
 * @returns {number} Индекс, на котором элемент остановился.
 */
function siftDown(heap, idx) {
  // Индекс максимального элемента
  let maxIdx = idx;

  // Индексы левого и правого дочерних элементов
  const left = 2 * idx;
  const right = 2 * idx + 1;

  // Существует ли левый дочерний элемент и больше ли он
  // текущего максимального элемента
  if (left < heap.length && heap[left] > heap[maxIdx]) {
    maxIdx = left;
  }

  // Существует ли правый дочерний элемент и больше ли он
  // текущего максимального элемента
  if (right < heap.length && heap[right] > heap[maxIdx]) {
    maxIdx = right;
  }

  // Если индекс максимального элемента не совпадает с исходным индексом
  if (maxIdx !== idx) {
    // Меняем местами текущий элемент с максимальным элементом
    [heap[idx], heap[maxIdx]] = [heap[maxIdx], heap[idx]];

    // Рекурсивно вызываем функцию для просеивания вниз дальше
    return siftDown(heap, maxIdx);
  }

  return maxIdx;
}

// Локальная проверка: проверяющая система вызывает только siftDown.
if (process.env.REMOTE_JUDGE !== 'true') {
  const assert = require('assert');

  const sample = [-1, 12, 1, 8, 3, 4, 7];

  assert.strictEqual(siftDown(sample, 2), 5);
  assert.deepStrictEqual(sample, [-1, 12, 4, 8, 3, 1, 7]);

  // Элемент уже на своем месте
  assert.strictEqual(siftDown([-1, 10, 5, 3], 1), 1);

  // Куча из одного элемента и обращение к листу
  assert.strictEqual(siftDown([-1, 7], 1), 1);
  assert.strictEqual(siftDown([-1, 9, 5, 3], 3), 3);

  console.log('l.js: OK');
}
