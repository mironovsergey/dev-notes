/**
 * M. Просеивание вверх
 *
 * https://contest.yandex.ru/contest/24809/problems/M/
 *
 * Напишите функцию, совершающую просеивание вверх в куче на максимум.
 * Гарантируется, что порядок элементов в куче может быть нарушен только
 * элементом, от которого запускается просеивание.
 *
 * Функция принимает в качестве аргументов массив, в котором хранятся элементы
 * кучи, и индекс элемента, от которого надо сделать просеивание вверх. Функция
 * должна вернуть индекс, на котором элемент оказался после просеивания. Также
 * необходимо изменить порядок элементов в переданном в функцию массиве.
 *
 * Индексация в массиве, содержащем кучу, начинается с единицы. Таким образом,
 * сыновья вершины на позиции v это 2v и 2v+1. Обратите внимание, что нулевой
 * элемент в передаваемом массиве фиктивный, вершина кучи соответствует 1-му
 * элементу.
 *
 * Формат ввода
 * Элементы кучи - целые числа, лежащие в диапазоне от −10^9 до 10^9. Все
 * элементы кучи уникальны. Передаваемый в функцию индекс лежит в диапазоне
 * от 1 до размера передаваемого массива. В куче содержится от 1 до 10^5
 * элементов.
 */

/**
 * Просеивает элемент вверх в куче на максимум.
 *
 * Итеративная версия: рекурсия здесь хвостовая, и цикл не расходует стек.
 * Нулевой элемент массива фиктивный, поэтому родитель вершины v лежит
 * на позиции ⌊v / 2⌋, а вершина кучи имеет индекс 1.
 *
 * Время: O(log n). Память: O(1).
 *
 * @param {number[]} heap Массив кучи с фиктивным нулевым элементом.
 * @param {number} idx Индекс просеиваемого элемента.
 * @returns {number} Индекс, на котором элемент остановился.
 */
function siftUp(heap, idx) {
  let currentIndex = idx;

  while (currentIndex > 1) {
    const parentIndex = Math.floor(currentIndex / 2);

    if (heap[currentIndex] > heap[parentIndex]) {
      // Если текущий элемент больше своего родителя, меняем их местами
      [heap[currentIndex], heap[parentIndex]] = [
        heap[parentIndex],
        heap[currentIndex],
      ];

      // Обновляем индекс текущего элемента
      currentIndex = parentIndex;
    } else {
      // Если текущий элемент меньше или равен своему родителю,
      // прекращаем просеивание
      break;
    }
  }

  return currentIndex;
}

/**
 * Рекурсивный вариант просеивания вверх - приведен для сравнения.
 *
 * Дает тот же результат, что и итеративная версия, но расходует O(log n)
 * стека. Для кучи из 10^5 элементов глубина не превышает 17, поэтому
 * переполнение здесь не грозит, - в отличие от рекурсии по высоте
 * несбалансированного дерева.
 *
 * Время: O(log n). Память: O(log n) на кадры стека вызовов.
 *
 * @param {number[]} heap Массив кучи с фиктивным нулевым элементом.
 * @param {number} index Индекс просеиваемого элемента.
 * @returns {number} Индекс, на котором элемент остановился.
 */
function siftUpRecursive(heap, index) {
  // Если индекс элемента меньше или равен 1, это означает,
  // что мы достигли корня кучи, поэтому возвращаем этот индекс,
  // так как просеивание вверх больше не требуется
  if (index <= 1) {
    return index;
  }

  // Индекс родителя текущего элемента в куче
  const parentIndex = Math.floor(index / 2);

  // Если текущий элемент больше своего родителя,
  // необходимо поменять их местами
  if (heap[index] > heap[parentIndex]) {
    // Обмен значениями текущего элемента и его родителя в куче
    [heap[index], heap[parentIndex]] = [heap[parentIndex], heap[index]];

    // Рекурсивный вызов функции для просеивания вверх дальше
    // относительно родителя
    return siftUpRecursive(heap, parentIndex);
  } else {
    // Если текущий элемент не больше своего родителя,
    // просеивание вверх завершается, и мы возвращаем
    // индекс текущего элемента
    return index;
  }
}

// Локальная проверка: проверяющая система вызывает только siftUp.
if (process.env.REMOTE_JUDGE !== 'true') {
  const assert = require('assert');

  const sample = [-1, 12, 6, 8, 3, 15, 7];

  assert.strictEqual(siftUp(sample, 5), 1);
  assert.deepStrictEqual(sample, [-1, 15, 12, 8, 3, 6, 7]);

  // Элемент уже на своем месте и вершина кучи
  assert.strictEqual(siftUp([-1, 10, 5, 3], 2), 2);
  assert.strictEqual(siftUp([-1, 10], 1), 1);

  // Обе версии дают одинаковый результат на случайных кучах
  for (let t = 0; t < 2000; t++) {
    const size = 1 + Math.floor(Math.random() * 20);
    const base = Array.from({ length: size }, () => Math.floor(Math.random() * 100));
    const index = 1 + Math.floor(Math.random() * size);
    const first = [-1, ...base];
    const second = [-1, ...base];

    assert.strictEqual(siftUp(first, index), siftUpRecursive(second, index));
    assert.deepStrictEqual(first, second);
  }

  console.log('m.js: OK');
}
