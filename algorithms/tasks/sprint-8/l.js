/**
 * L. Подсчет префикс-функции
 *
 * https://contest.yandex.ru/contest/26131/problems/L/
 *
 * В этой задаче вам необходимо посчитать префикс-функцию для заданной строки.
 *
 * Формат ввода
 * На вход подается строка, состоящая из строчных латинских букв. Длина строки
 * не превосходит 10^6.
 *
 * Формат вывода
 * Если длина входной строки L, то выведите через пробел L целых неотрицательных
 * чисел - массив значений префикс-функции исходной строки.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const s = readLine();

  process.stdout.write(`${computePrefixFunction(s).join(' ')}`);
}

/**
 * Вычисляет префикс-функцию строки.
 *
 * Значение pi[i] строится из pi[i-1]: сначала делается попытка продлить
 * предыдущее совпадение на один символ, а при неудаче длина откатывается
 * к pi[k-1] - следующему по величине кандидату - и попытка повторяется.
 *
 * Внутренний цикл не делает алгоритм квадратичным: переменная k растет не
 * более чем на единицу за итерацию внешнего цикла, а каждый откат уменьшает
 * ее минимум на единицу, поэтому суммарное число откатов не превосходит n.
 *
 * Время: O(n). Память: O(n).
 *
 * @param {string} s Строка.
 * @returns {number[]} Значения префикс-функции.
 */
function computePrefixFunction(s) {
  const n = s.length;
  const pi = new Array(n).fill(0);
  let k = 0;

  for (let i = 1; i < n; i++) {
    while (k > 0 && s[k] !== s[i]) {
      k = pi[k - 1];
    }
    if (s[k] === s[i]) {
      k++;
    }
    pi[i] = k;
  }

  return pi;
}

run(solve);
