/**
 * E. Вставка строк
 *
 * https://contest.yandex.ru/contest/26131/problems/E/
 *
 * У Риты была строка s, Гоша подарил ей на 8 марта еще n других строк tᵢ,
 * 1 ≤ i ≤ n. Теперь Рита думает, куда их лучше поставить. Один из вариантов -
 * расположить подаренные строки внутри имеющейся строки s, поставив строку tᵢ
 * сразу после символа строки s с номером kᵢ (в частности, если kᵢ = 0,
 * то строка вставляется в самое начало s).
 *
 * Помогите Рите и определите, какая строка получится после вставки в s всех
 * подаренных Гошей строк.
 *
 * Формат ввода
 * В первой строке дана строка s. Строка состоит из строчных букв английского
 * алфавита, не бывает пустой и ее длина не превышает 10^5 символов.
 *
 * Во второй строке записано количество подаренных строк - натуральное число n,
 * 1 ≤ n ≤ 10^5.
 *
 * В каждой из следующих n строк через пробел записаны пары tᵢ и kᵢ. Строка tᵢ
 * состоит из маленьких латинских букв и не бывает пустой. kᵢ - целое число,
 * лежащее в диапазоне от 0 до |s|. Все числа kᵢ уникальны. Гарантируется, что
 * суммарная длина всех строк tᵢ не превосходит 10^5.
 *
 * Формат вывода
 * Выведите получившуюся в результате вставок строку.
 */

const { run, readInt, readLine } = require('../../lib/io');

function solve() {
  const s = readLine();
  const n = readInt();
  const inserts = [];

  for (let i = 0; i < n; i++) {
    const [t, k] = readLine().trim().split(' ');
    inserts.push([t, Number(k)]);
  }

  process.stdout.write(`${insertAll(s, inserts)}`);
}

/**
 * Вставляет все подстроки в исходную строку за один проход.
 *
 * Вставки группируются по позиции; несколько вставок в одну позицию
 * склеиваются в порядке поступления. Затем результат собирается одним
 * проходом по исходной строке.
 *
 * Выполнять вставки по одной было бы O(k · |s|): каждая создает новую строку
 * целиком. Здесь строка обходится один раз.
 *
 * Время: O(|s| + суммарной длины вставок). Память: O того же порядка.
 *
 * @param {string} s Исходная строка.
 * @param {Array<[string, number]>} inserts Вставки в виде [подстрока, позиция].
 * @returns {string} Строка после всех вставок.
 */
function insertAll(s, inserts) {
  const map = new Map();

  for (const [t, k] of inserts) {
    if (!map.has(k)) {
      map.set(k, t);
    } else {
      map.set(k, map.get(k) + t);
    }
  }

  let result = '';
  let i = 0;

  while (i <= s.length) {
    if (map.has(i)) {
      const t = map.get(i);
      let j = 0;

      while (j < t.length) {
        result += t[j];
        j++;
      }
    }

    if (i < s.length) {
      result += s[i];
    }

    i++;
  }

  return result;
}

function insertAllIterative(s, inserts) {
  let result = '';
  let i = 0;

  while (i <= s.length) {
    for (let m = 0; m < inserts.length; m++) {
      const [t, k] = inserts[m];

      if (k === i) {
        let j = 0;

        while (j < t.length) {
          result += t[j];
          j++;
        }
      }
    }

    if (i < s.length) {
      result += s[i];
    }

    i++;
  }

  return result;
}

run(solve);
