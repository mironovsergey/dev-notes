/**
 * B. Пограничный контроль
 *
 * https://contest.yandex.ru/contest/26131/problems/B/
 *
 * Представьте, что вы работаете пограничником и постоянно проверяете документы
 * людей по записи из базы. При этом допустима ситуация, когда имя человека
 * в базе отличается от имени в паспорте на одну замену, одно удаление или одну
 * вставку символа. Если один вариант имени может быть получен из другого
 * удалением одного символа, то человека пропустят через границу. А вот если
 * есть какое-либо второе изменение, то человек грустно поедет домой или
 * в посольство.
 *
 * Например, если первый вариант - это «Лена», а второй - «Лера», то девушку
 * пропустят. Также человека пропустят, если в базе записано «Коля», а в
 * паспорте - «оля».
 *
 * Однако вариант, когда в базе числится «Иннокентий», а в паспорте написано
 * «ннакентий», уже не сработает. Не пропустят также человека, у которого
 * в паспорте записан «Иинннокентий», а вот «Инннокентий» спокойно пересечет
 * границу.
 *
 * Напишите программу, которая сравнивает имя в базе с именем в паспорте
 * и решает, пропускать человека или нет. В случае равенства двух строк -
 * путешественника, естественно, пропускают.
 *
 * Формат ввода
 * В первой строке дано имя из паспорта.
 * Во второй строке - имя из базы.
 * Обе строки состоят из строчных букв английского алфавита. Размер каждой
 * строки не превосходит 100 000 символов.
 *
 * Формат вывода
 * Выведите «OK», если человека пропустят, или «FAIL» в противном случае.
 */

const { run, readLine } = require('../../lib/io');

function solve() {
  const s1 = readLine();
  const s2 = readLine();

  process.stdout.write(`${canTransform(s1, s2) ? 'OK' : 'FAIL'}`);
}

/**
 * Проверяет, можно ли получить одну строку из другой не более чем одной
 * операцией: вставкой, удалением или заменой символа.
 *
 * Это расстояние Левенштейна, ограниченное единицей, но полная таблица здесь
 * не нужна: разница длин больше единицы сразу означает отрицательный ответ,
 * а в остальных случаях достаточно одного прохода двумя указателями.
 *
 * При равных длинах допускается одно расхождение - замена. При разнице в один
 * символ указатель по длинной строке сдвигается на одну позицию вперед, что
 * соответствует вставке или удалению.
 *
 * Время: O(|str1| + |str2|). Память: O(1).
 *
 * @param {string} str1 Первая строка.
 * @param {string} str2 Вторая строка.
 * @returns {boolean} true, если строки различаются не более чем одной операцией.
 */
function canTransform(str1, str2) {
  const len1 = str1.length;
  const len2 = str2.length;

  if (Math.abs(len1 - len2) > 1) {
    return false;
  }

  if (len1 > len2) {
    return canTransform(str2, str1);
  }

  let diff = 0;
  let i = 0;
  let j = 0;

  while (i < len1 && j < len2) {
    if (str1[i] !== str2[j]) {
      if (++diff > 1) {
        return false;
      }

      if (len1 < len2) {
        j++;
      } else {
        i++;
        j++;
      }
    } else {
      i++;
      j++;
    }
  }

  return true;
}

run(solve);
